#!/usr/bin/env python3
"""tools/auto_stub.py

Parse missing PS5 ``sce`` function declarations and emit C++ PRX stub
definitions formatted according to the project's C++ coding conventions
(AnyPS5 style).

Conventions applied
-------------------
* 4 spaces of indentation (tabs are forbidden)
* K&R brace style: opening brace on the same line as the signature
* Maximum line length of 120 characters; long parameter lists are wrapped
* Stub bodies call ``SCE_NOT_IMPLEMENTED("<name>")`` and return a
  not-implemented error value matching the C return type

Input format: one function declaration per line. Blank lines and lines
starting with ``#`` are ignored.

    int sceKernelCreateThread(const char *name, SceKernelThreadEntry entry,
                              int priority, unsigned int stackSize,
                              unsigned int attr, const void *arg)

Usage::

    python tools/auto_stub.py [input_file] [output_file]

If ``input_file`` is omitted, declarations are read from stdin.
If ``output_file`` is omitted, the generated stubs are written to stdout.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import List, Optional, Tuple

# --------------------------------------------------------------------------- #
# Project C++ coding conventions (AnyPS5 style)
# --------------------------------------------------------------------------- #
INDENT = "    "          # 4 spaces; tabs are forbidden
MAX_LINE_LENGTH = 120    # hard wrap limit for generated source lines
BRACE_STYLE = "k&r"      # opening brace on the signature line

# Default "not implemented" return value keyed by C return type.
DEFAULT_RETURN: dict[str, Optional[str]] = {
    "void": None,
    "int": "SCE_KERNEL_ERROR_NOT_IMPLEMENTED",
    "SceInt32": "SCE_KERNEL_ERROR_NOT_IMPLEMENTED",
    "SceUInt32": "SCE_KERNEL_ERROR_NOT_IMPLEMENTED",
    "uint32_t": "SCE_KERNEL_ERROR_NOT_IMPLEMENTED",
    "SceInt64": "SCE_KERNEL_ERROR_NOT_IMPLEMENTED",
    "SceUInt64": "SCE_KERNEL_ERROR_NOT_IMPLEMENTED",
    "SceSize": "SCE_KERNEL_ERROR_NOT_IMPLEMENTED",
    "SceOff": "SCE_KERNEL_ERROR_NOT_IMPLEMENTED",
    "SceUid": "SCE_KERNEL_ERROR_NOT_IMPLEMENTED",
    "SceBool": "SCE_FALSE",
    "bool": "false",
    "float": "0.0f",
    "double": "0.0",
    "char": "'\\0'",
    "unsigned char": "0",
    "unsigned int": "0u",
    "unsigned long": "0ul",
    "unsigned long long": "0ull",
    "long": "0l",
    "long long": "0ll",
    "short": "0",
    "unsigned short": "0u",
}

STUB_FILE_HEADER = """\
// Auto-generated by tools/auto_stub.py -- DO NOT EDIT BY HAND.
// This file contains PRX stub definitions for missing PS5 sce functions.
// Implement the real functionality and remove the SCE_NOT_IMPLEMENTED() calls
// once the function is implemented.

"""

# Matches:  return_type function_name ( params )
# The return type may contain spaces, * / & / const / :: (e.g. "const char *").
DECL_RE = re.compile(
    r"^(?P<ret>[A-Za-z_][\w\s\*\&\:\<\>\,]+?)\s+"
    r"(?P<name>[A-Za-z_]\w*)\s*"
    r"\(\s*(?P<params>.*?)\s*\)\s*$"
)


def split_params(params: str) -> List[str]:
    """Split a parameter list on top-level commas (ignoring nested parens)."""
    if not params.strip():
        return []
    parts: List[str] = []
    current: List[str] = []
    depth = 0
    for ch in params:
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append("".join(current).strip())
            current = []
        else:
            current.append(ch)
    if current:
        parts.append("".join(current).strip())
    return [p for p in parts if p]


def default_return_for(ret_type: str) -> str:
    """Return the stub-body ``return`` expression for a given C return type."""
    key = ret_type.strip()
    if key in DEFAULT_RETURN:
        val = DEFAULT_RETURN[key]
        return val if val is not None else ""
    # Fall back to the last token (handles "const char *", etc.).
    last = key.split()[-1].strip("*&")
    val = DEFAULT_RETURN.get(last)
    return val if val is not None else "0"


def build_signature(ret_type: str, name: str, params: str) -> str:
    """Build a formatted function signature with an opening brace."""
    parts = split_params(params)
    if not parts:
        single = f"{ret_type} {name}(void)"
        return single + " {" if len(single) <= MAX_LINE_LENGTH else single + "\n{"

    single = f"{ret_type} {name}({', '.join(parts)})"
    if len(single) <= MAX_LINE_LENGTH:
        return single + " {"

    # Wrap the parameter list across multiple indented lines.
    lines = [f"{ret_type} {name}("]
    for i, p in enumerate(parts):
        comma = "," if i < len(parts) - 1 else ""
        lines.append(INDENT + p + comma)
    lines.append(") {")
    return "\n".join(lines)


def generate_stub(ret_type: str, name: str, params: str) -> str:
    """Generate a single C++ PRX stub definition."""
    signature = build_signature(ret_type, name, params)
    ret = default_return_for(ret_type)
    ret_stmt = f"{INDENT}return {ret};" if ret else ""
    body = f"{INDENT}SCE_NOT_IMPLEMENTED(\"{name}\");\n"
    if ret_stmt:
        body += ret_stmt + "\n"
    body += f"{INDENT}}}\n"
    return signature + "\n" + body


def parse_declaration(line: str) -> Optional[Tuple[str, str, str]]:
    """Parse a single declaration into (return_type, name, params)."""
    m = DECL_RE.match(line.strip())
    if not m:
        return None
    return m.group("ret").strip(), m.group("name"), m.group("params").strip()


def parens_balanced(text: str) -> bool:
    """Return True if round parentheses in *text* are balanced."""
    depth = 0
    for ch in text:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth < 0:
                return False
    return depth == 0


def read_declarations(source) -> List[Tuple[str, str, str]]:
    """Read declarations from a file-like object, skipping blanks/comments.

    Continuation lines are joined until the parentheses are balanced, so
    declarations may span multiple source lines.
    """
    decls: List[Tuple[str, str, str]] = []
    buffer: List[str] = []

    def flush() -> None:
        nonlocal buffer
        if not buffer:
            return
        joined = " ".join(buffer)
        buffer = []
        parsed = parse_declaration(joined)
        if parsed is None:
            print(f"warning: skipping unparsable declaration: {joined!r}",
                  file=sys.stderr)
        else:
            decls.append(parsed)

    for raw in source:
        line = raw.strip()
        if not line or line.startswith("#"):
            flush()
            continue
        buffer.append(line)
        if parens_balanced(" ".join(buffer)):
            flush()
    flush()
    return decls


def generate_stubs(decls: List[Tuple[str, str, str]]) -> str:
    """Generate the full stub file content from parsed declarations."""
    out = [STUB_FILE_HEADER]
    for ret_type, name, params in decls:
        out.append(generate_stub(ret_type, name, params))
        out.append("\n")
    return "".join(out)


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate C++ PRX stub definitions for missing PS5 sce "
                    "function declarations.",
    )
    parser.add_argument("input", nargs="?", help="declarations file (default: stdin)")
    parser.add_argument("output", nargs="?", help="output .cpp file (default: stdout)")
    args = parser.parse_args(argv)

    if args.input:
        with open(args.input, "r", encoding="utf-8") as fh:
            decls = read_declarations(fh)
    else:
        decls = read_declarations(sys.stdin)

    content = generate_stubs(decls)

    if args.output:
        out_path = Path(args.output)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(content, encoding="utf-8")
        print(f"wrote {len(decls)} stub(s) to {out_path}")
    else:
        sys.stdout.write(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
