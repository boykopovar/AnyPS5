pub const ABI_VERSION: u32 = 1;

pub const STUB_STRIDE: u64 = 16;

pub mod cpu {
    pub const GPR: u64 = 0x000;
    pub const RIP: u64 = 0x080;
    pub const RFLAGS: u64 = 0x088;
    pub const FS_BASE: u64 = 0x090;
    pub const GS_BASE: u64 = 0x098;
    pub const STOP_RIP: u64 = 0x0A0;
    pub const MXCSR: u64 = 0x0A8;
    pub const YMM: u64 = 0x0C0;
    pub const X87_ST: u64 = 0x2C0;
    pub const X87_TOP: u64 = 0x300;
    pub const X87_FCW: u64 = 0x304;
    pub const X87_FSW: u64 = 0x306;
    pub const X87_TAGS: u64 = 0x308;
    pub const SIZE: u64 = 0x400;
    pub const ALIGN: u64 = 64;

    pub const fn gpr(index: u32) -> u64 {
        GPR + 8 * index as u64
    }

    pub const fn ymm(index: u32) -> u64 {
        YMM + 32 * index as u64
    }
}

pub mod names {
    pub const MEMORY: &str = "memory";
    pub const IMAGE_BASE_PREFIX: &str = "__aps5_image_base_";
    pub const STUB_BASE: &str = "__aps5_stub_base";
    pub const ADDR_MAP: &str = "__aps5_addr_map";
    pub const DISPATCH: &str = "__aps5_dispatch";
    pub const ABI_VERSION_EXPORT: &str = "__aps5_abi_version";
    pub const NID_MODULE: &str = "nid";
    pub const RUNTIME_MODULE: &str = "aps5";
    pub const CPUID: &str = "cpuid";
    pub const RDTSC: &str = "rdtsc";
    pub const CMPXCHG16B: &str = "cmpxchg16b";
    pub const UNRESOLVED_INDIRECT: &str = "unresolved_indirect";
    pub const UNSUPPORTED: &str = "unsupported";
    pub const CUSTOM_SECTION: &str = "anyps5.images";
}

pub mod addr_map {
    pub const HEADER_SIZE: u64 = 16;
    pub const ENTRY_SIZE: u64 = 16;
    pub const EMPTY_KEY: u64 = u64::MAX;
    pub const IMAGE_SHIFT: u32 = 48;

    pub const fn key(image: u32, offset: u64) -> u64 {
        ((image as u64) << IMAGE_SHIFT) | offset
    }

    pub const fn hash(key: u64) -> u64 {
        let mixed = key.wrapping_mul(0x9e37_79b9_7f4a_7c15);
        mixed ^ (mixed >> 32)
    }
}

pub fn c_header() -> String {
    let mut header = String::new();
    let mut line = |text: String| {
        header.push_str(&text);
        header.push('\n');
    };
    line("// Generated by anyps5-wasm-aot. Do not edit.".into());
    line("#pragma once".into());
    line(format!("#define APS5_WASM_ABI_VERSION {ABI_VERSION}u"));
    line(format!("#define APS5_WASM_STUB_STRIDE {STUB_STRIDE}u"));
    for (name, value) in [
        ("GPR", cpu::GPR),
        ("RIP", cpu::RIP),
        ("RFLAGS", cpu::RFLAGS),
        ("FS_BASE", cpu::FS_BASE),
        ("GS_BASE", cpu::GS_BASE),
        ("STOP_RIP", cpu::STOP_RIP),
        ("MXCSR", cpu::MXCSR),
        ("YMM", cpu::YMM),
        ("X87_ST", cpu::X87_ST),
        ("X87_TOP", cpu::X87_TOP),
        ("X87_FCW", cpu::X87_FCW),
        ("X87_FSW", cpu::X87_FSW),
        ("X87_TAGS", cpu::X87_TAGS),
        ("SIZE", cpu::SIZE),
        ("ALIGN", cpu::ALIGN),
    ] {
        line(format!("#define APS5_WASM_CPU_{name} {value:#x}u"));
    }
    for (name, value) in [
        ("MEMORY", names::MEMORY),
        ("IMAGE_BASE_PREFIX", names::IMAGE_BASE_PREFIX),
        ("STUB_BASE", names::STUB_BASE),
        ("ADDR_MAP", names::ADDR_MAP),
        ("DISPATCH", names::DISPATCH),
        ("ABI_VERSION_EXPORT", names::ABI_VERSION_EXPORT),
        ("NID_MODULE", names::NID_MODULE),
        ("RUNTIME_MODULE", names::RUNTIME_MODULE),
        ("CUSTOM_SECTION", names::CUSTOM_SECTION),
    ] {
        line(format!("#define APS5_WASM_NAME_{name} \"{value}\""));
    }
    header
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn header_names_every_cpu_offset() {
        let header = c_header();
        assert!(header.contains("#define APS5_WASM_CPU_YMM 0xc0u"));
        assert!(header.contains("#define APS5_WASM_CPU_SIZE 0x400u"));
        assert!(header.contains("#define APS5_WASM_ABI_VERSION 1u"));
    }

    #[test]
    fn gpr_offsets_follow_encoding_order() {
        assert_eq!(cpu::gpr(4), 0x20);
        assert_eq!(cpu::gpr(15), 0x78);
        assert_eq!(cpu::ymm(15), 0x2a0);
    }
}
