template<std::size_t Size>
std::uint32_t DefineTable(SpirvEmitterState& state, const std::array<std::uint32_t, Size>& values) {
    std::array<std::uint32_t, Size> words{};
    for (std::size_t index = 0; index < Size; ++index) words[index] = ConstantU32(state, values[index]);
    const auto arrayType = state.module.Type(spv::OpTypeArray, TypeU32(state), ConstantU32(state, static_cast<std::uint32_t>(Size)));
    const auto table = state.module.Constant(spv::OpConstantComposite, arrayType, std::span<const std::uint32_t>(words));
    return state.module.DefineInitializedGlobalVariable(TypePointer(state, spv::StorageClassPrivate, arrayType), spv::StorageClassPrivate, table);
}

std::uint32_t LoadTable(SpirvEmitterState& state, std::uint32_t table, std::uint32_t index) {
    const auto pointer = state.module.AllocateId();
    state.module.AddFunction(spv::OpAccessChain, TypePointer(state, spv::StorageClassPrivate, TypeU32(state)), pointer, table, index);
    const auto value = state.module.AllocateId();
    state.module.AddFunction(spv::OpLoad, TypeU32(state), value, pointer);
    return value;
}

std::array<std::uint32_t, 2> MultiplyExtended(SpirvEmitterState& state, std::uint32_t lhs, std::uint32_t rhs) {
    const auto product = state.module.AllocateId();
    state.module.AddFunction(spv::OpUMulExtended, TypeU32Pair(state), product, lhs, rhs);
    std::array<std::uint32_t, 2> words{state.module.AllocateId(), state.module.AllocateId()};
    state.module.AddFunction(spv::OpCompositeExtract, TypeU32(state), words[0], product, 0u);
    state.module.AddFunction(spv::OpCompositeExtract, TypeU32(state), words[1], product, 1u);
    return words;
}

std::uint32_t ReciprocalCorrection(SpirvEmitterState& state, std::uint32_t mantissa) {
    const auto u32 = TypeU32(state);
    const auto boolean = TypeBool(state);
    const auto op = [&](spv::Op opcode, std::uint32_t lhs, std::uint32_t value) { return Binary(state, opcode, u32, lhs, ConstantU32(state, value)); };
    const auto starts = DefineTable(state, ReciprocalCorrectionStarts);
    const auto corrections = DefineTable(state, ReciprocalCorrections);
    const auto halfword = [&](std::uint32_t table, std::uint32_t index, std::uint32_t last) {
        const auto clamped = Select(state, u32, Binary(state, spv::OpULessThan, boolean, index, ConstantU32(state, last)), index, ConstantU32(state, last));
        const auto word = LoadTable(state, table, op(spv::OpShiftRightLogical, clamped, 1u));
        return op(spv::OpBitwiseAnd, Binary(state, spv::OpShiftRightLogical, u32, word, op(spv::OpShiftLeftLogical, op(spv::OpBitwiseAnd, clamped, 1u), 4u)), 0xffffu);
    };
    const auto lastStart = static_cast<std::uint32_t>(ReciprocalCorrectionStarts.size() * 2u - 1u);
    const auto lastCorrection = static_cast<std::uint32_t>(ReciprocalCorrections.size() * 2u - 1u);
    const auto bucket = op(spv::OpShiftRightLogical, mantissa, 12u);
    const auto key = op(spv::OpBitwiseAnd, mantissa, 0xfffu);
    const auto end = halfword(starts, op(spv::OpIAdd, bucket, 1u), lastStart);
    auto first = halfword(starts, bucket, lastStart);
    auto remaining = Binary(state, spv::OpISub, u32, end, first);
    for (const std::uint32_t step : {8u, 4u, 2u, 1u}) {
        const auto probe = op(spv::OpBitwiseAnd, halfword(corrections, op(spv::OpIAdd, first, step - 1u), lastCorrection), 0xfffu);
        const auto inside = Binary(state, spv::OpULessThanEqual, boolean, ConstantU32(state, step), remaining);
        const auto skip = Binary(state, spv::OpLogicalAnd, boolean, inside, Binary(state, spv::OpULessThan, boolean, probe, key));
        first = Select(state, u32, skip, op(spv::OpIAdd, first, step), first);
        remaining = Select(state, u32, skip, op(spv::OpISub, remaining, step), remaining);
    }
    const auto entry = halfword(corrections, first, lastCorrection);
    const auto hit = Binary(state, spv::OpLogicalAnd, boolean, Binary(state, spv::OpULessThan, boolean, first, end), Binary(state, spv::OpIEqual, boolean, op(spv::OpBitwiseAnd, entry, 0xfffu), key));
    const auto delta = Select(state, u32, Binary(state, spv::OpINotEqual, boolean, op(spv::OpBitwiseAnd, entry, 0x1000u), ConstantU32(state, 0u)), ConstantU32(state, 1u), ConstantU32(state, 0xffffffffu));
    return Select(state, u32, hit, delta, ConstantU32(state, 0u));
}

