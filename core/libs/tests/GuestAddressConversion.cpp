static unsigned HexValue(char digit) { return digit <= '9' ? static_cast<unsigned>(digit - '0') : static_cast<unsigned>(digit - 'a' + 10); }

static std::size_t FromHex(const char* hex, unsigned char* out) {
    std::size_t index = 0;
    for (; hex[2 * index]; ++index) out[index] = static_cast<unsigned char>(HexValue(hex[2 * index]) << 4 | HexValue(hex[2 * index + 1]));
    return index;
}

static bool SameBytes(const void* data, const char* hex) {
    const auto* bytes = static_cast<const unsigned char*>(data);
    for (std::size_t index = 0; hex[2 * index]; ++index)
        if (bytes[index] != (HexValue(hex[2 * index]) << 4 | HexValue(hex[2 * index + 1]))) return false;
    return true;
}

template <typename TCall>
static bool Throws(TCall call) {
    try {
        call();
    } catch (const std::runtime_error&) {
        return true;
    }
    return false;
}

static char Wide[70000];

static void CheckConsolePton() {
    for (const PtonCase& sample : ConsolePton) {
        unsigned char destination[16];
        std::memset(destination, 0xAA, sizeof(destination));
        *__error_nid_postfix() = 0;
        const int result = sample.plain ? inet_pton_nid_postfix(sample.family, sample.text, destination)
                                        : __inet_pton_nid_postfix(sample.family, sample.text, destination);

        Require(result == sample.result);
        Require(*__error_nid_postfix() == sample.error);
        Require(SameBytes(destination, sample.bytes));
    }
}

static void CheckConsoleNtop() {
    for (const NtopCase& sample : ConsoleNtop) {
        unsigned char source[16]{};
        FromHex(sample.source, source);
        std::memset(Wide, 'Z', sizeof(Wide));
        *__error_nid_postfix() = 0;
        const char* result = sample.plain ? inet_ntop_nid_postfix(sample.family, source, Wide, sample.size)
                                          : __inet_ntop_nid_postfix(sample.family, source, Wide, sample.size);

        Require(result == (sample.succeeds ? Wide : nullptr));
        Require(*__error_nid_postfix() == sample.error);
        Require(SameBytes(Wide, sample.bytes));
        if (!sample.lastTouched && sample.succeeds) continue;
        const std::size_t shown = std::strlen(sample.bytes) / 2;
        for (std::size_t index = shown; index < sample.lastTouched; ++index) Require(Wide[index] != 'Z');
        for (std::size_t index = sample.lastTouched; index < sizeof(Wide); ++index) Require(Wide[index] == 'Z');
    }
}

static void CheckConsolePadding(const PadCase* samples, std::size_t count, Ntop ntop) {
    for (std::size_t sample = 0; sample < count; ++sample) {
        unsigned char source[16]{};
        FromHex(samples[sample].source, source);
        std::memset(Wide, 'Z', sizeof(Wide));
        Require(ntop(samples[sample].family, source, Wide, samples[sample].size) == Wide);
        for (std::size_t index = std::strlen(Wide); index < samples[sample].lastTouched; ++index) Require(Wide[index] == '\0');
        for (std::size_t index = samples[sample].lastTouched; index < sizeof(Wide); ++index) Require(Wide[index] == 'Z');
    }
}

