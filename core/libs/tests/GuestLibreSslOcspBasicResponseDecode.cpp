constexpr unsigned char NonceOid[] {0x2b, 0x06, 0x01, 0x05, 0x05, 0x07, 0x30, 0x01, 0x02};
constexpr unsigned char NonceValue[] {0x04, 0x08, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08};

using Bytes = std::vector<unsigned char>;

Bytes Join(std::initializer_list<Bytes> parts) {
    Bytes result;
    for (const auto& part : parts) result.insert(result.end(), part.begin(), part.end());
    return result;
}

Bytes Tlv(unsigned char tag, std::initializer_list<Bytes> parts) {
    const Bytes content = Join(parts);
    Bytes result {tag};
    if (content.size() < 0x80) {
        result.push_back(static_cast<unsigned char>(content.size()));
    } else if (content.size() < 0x100) {
        result.insert(result.end(), {0x81, static_cast<unsigned char>(content.size())});
    } else {
        result.insert(result.end(), {0x82, static_cast<unsigned char>(content.size() >> 8), static_cast<unsigned char>(content.size())});
    }
    result.insert(result.end(), content.begin(), content.end());
    return result;
}

Bytes Raw(const unsigned char* data, std::size_t size) {
    return Bytes(data, data + size);
}

const Bytes BasicType {0x06, 0x09, 0x2b, 0x06, 0x01, 0x05, 0x05, 0x07, 0x30, 0x01, 0x01};
const Bytes Eoc {0x00, 0x00};

Bytes Response(const Bytes& basic, const Bytes& type = BasicType) {
    return Tlv(0x30, {{0x0a, 0x01, 0x00}, Tlv(0xa0, {Tlv(0x30, {type, Tlv(0x04, {basic})})})});
}

Bytes BasicOf(const unsigned char* der, std::size_t size) {
    const unsigned char* input = der;
    auto* response = d2i_OCSP_RESPONSE_nid_postfix(nullptr, &input, static_cast<std::int64_t>(size));
    Require(response && response->responseBytes);
    const auto* octets = static_cast<LibreSslOcspResponseBytes*>(response->responseBytes)->response;
    Bytes basic(octets->data, octets->data + octets->length);
    OCSP_RESPONSE_free_nid_postfix(response);
    return basic;
}

constexpr std::uint64_t Asn1(int reason) {
    return (std::uint64_t{13} << 24) | (std::uint64_t{0xfff} << 12) | static_cast<std::uint64_t>(reason);
}

constexpr std::uint64_t Ocsp(int reason) {
    return (std::uint64_t{39} << 24) | (std::uint64_t{0xfff} << 12) | static_cast<std::uint64_t>(reason);
}

std::vector<std::uint64_t> Errors() {
    std::vector<std::uint64_t> errors;
    while (const auto error = ERR_get_error_nid_postfix()) errors.push_back(error);
    return errors;
}

void RequireErrors(const std::vector<int>& reasons, std::source_location location = std::source_location::current()) {
    std::vector<std::uint64_t> expected;
    for (const int reason : reasons) expected.push_back(Asn1(reason));
    Require(Errors() == expected, location);
}

LibreSslOcspResponse* Decode(const Bytes& der) {
    const unsigned char* input = der.data();
    auto* response = d2i_OCSP_RESPONSE_nid_postfix(nullptr, &input, static_cast<std::int64_t>(der.size()));
    Require(response && input == der.data() + der.size());
    return response;
}

template<std::size_t TSize> bool Same(const Asn1String* string, int type, const unsigned char (&expected)[TSize]) {
    return string && string->type == type && string->length == static_cast<int>(TSize) && string->flags == 0 &&
        std::memcmp(string->data, expected, TSize) == 0;
}

template<std::size_t TSize> bool SameObject(const LibreSslAsn1Object* object, const unsigned char (&expected)[TSize]) {
    return object && object->length == static_cast<int>(TSize) && object->flags == 0x09 && object->nid == 0 &&
        std::memcmp(object->data, expected, TSize) == 0;
}

