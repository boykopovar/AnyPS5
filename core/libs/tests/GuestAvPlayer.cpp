        std::memcpy(raw.data(), &head, Ps5AutoStart);
        raw[Ps5AutoStart] = autoStart ? 1 : 0;
        if (!autoStart) std::fill(raw.begin() + static_cast<std::ptrdiff_t>(Ps5ThreadParameters), raw.end(), std::uint8_t{1});
