int main() {
    FreeType::GuestLibrary* guestLibrary = nullptr;
    FT_Library nativeLibrary = nullptr;
    Require(FT_Init_FreeType_nid_postfix(&guestLibrary) == 0 && FT_Init_FreeType(&nativeLibrary) == 0);
    FreeType::GuestFaceRec* guest = nullptr;
    FT_Face native = nullptr;
    Require(FT_New_Memory_Face_nid_postfix(guestLibrary, ColorFont.data(), static_cast<std::int64_t>(ColorFont.size()), 0, &guest) == 0);
    Require(FT_New_Memory_Face(nativeLibrary, ColorFont.data(), static_cast<FT_Long>(ColorFont.size()), 0, &native) == 0);

    LegacyFreeType::GuestPaletteData data{};
    FT_Palette_Data nativeData{};
    Require(FT_Palette_Data_Get_nid_postfix(guest, &data) == 0 && FT_Palette_Data_Get(native, &nativeData) == 0);
    Require(data.num_palettes == 2 && data.num_palettes == nativeData.num_palettes && data.num_palette_entries == nativeData.num_palette_entries);
    for (std::uint16_t index = 0; index < 2; ++index) {
        Require(data.palette_name_ids[index] == nativeData.palette_name_ids[index] && data.palette_flags[index] == nativeData.palette_flags[index]);
        Require(data.palette_entry_name_ids[index] == nativeData.palette_entry_name_ids[index]);
    }
    Require(FT_Palette_Data_Get_nid_postfix(guest, nullptr) == FT_Err_Invalid_Argument);
    Require(FT_Palette_Data_Get_nid_postfix(nullptr, &data) == FT_Err_Invalid_Face_Handle);

    for (std::uint16_t index = 0; index < 3; ++index) {
        LegacyFreeType::GuestColor* palette = nullptr;
        FT_Color* nativePalette = nullptr;
        const auto error = FT_Palette_Select_nid_postfix(guest, index, &palette);
        Require(error == FT_Palette_Select(native, index, &nativePalette));
        if (error == 0) Require(palette && std::memcmp(palette, nativePalette, 2 * sizeof(FT_Color)) == 0);
        Require(FT_Palette_Select_nid_postfix(guest, index, nullptr) == error);
    }
    LegacyFreeType::GuestColor* palette = nullptr;
    Require(FT_Palette_Select_nid_postfix(guest, 0, &palette) == 0);
    Require(palette[0].red == 0xff && palette[0].green == 0 && palette[0].blue == 0 && palette[0].alpha == 0xff);
    Require(FT_Palette_Select_nid_postfix(nullptr, 0, &palette) == FT_Err_Invalid_Face_Handle);

    for (const std::uint32_t baseGlyph : {0u, 1u, 2u, 4u}) CheckLayers(guest, native, baseGlyph);
    LegacyFreeType::GuestLayerIterator iterator{};
    std::uint32_t glyph = 0;
    std::uint32_t color = 0;
    Require(FT_Get_Color_Glyph_Layer_nid_postfix(guest, 1, &glyph, &color, &iterator) == 1 && glyph == 2 && color == 0 && iterator.num_layers == 2);
    Require(FT_Get_Color_Glyph_Layer_nid_postfix(guest, 1, &glyph, &color, &iterator) == 1 && glyph == 3 && color == 1);
    Require(FT_Get_Color_Glyph_Layer_nid_postfix(guest, 1, &glyph, &color, &iterator) == 0);
    iterator = {};
    Require(FT_Get_Color_Glyph_Layer_nid_postfix(guest, 1, &glyph, &color, nullptr) == 0);
    Require(FT_Get_Color_Glyph_Layer_nid_postfix(guest, 1, nullptr, &color, &iterator) == 0 && !iterator.p);
    Require(FT_Get_Color_Glyph_Layer_nid_postfix(nullptr, 1, &glyph, &color, &iterator) == 0);

    Require(FT_Done_Face_nid_postfix(guest) == 0 && FT_Done_Face(native) == 0);
    Require(FT_Done_FreeType_nid_postfix(guestLibrary) == 0 && FT_Done_FreeType(nativeLibrary) == 0);
    return 0;
}
