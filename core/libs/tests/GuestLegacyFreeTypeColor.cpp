void Require(bool value) {
    if (!value) std::abort();
}

void CheckLayers(FreeType::GuestFaceRec* guest, FT_Face native, std::uint32_t baseGlyph) {
    LegacyFreeType::GuestLayerIterator guestIterator{};
    FT_LayerIterator nativeIterator{};
    for (int step = 0; step < 4; ++step) {
        std::uint32_t guestGlyph = 0xffff;
        std::uint32_t guestColor = 0xffff;
        FT_UInt nativeGlyph = 0xffff;
        FT_UInt nativeColor = 0xffff;
        const auto found = FT_Get_Color_Glyph_Layer_nid_postfix(guest, baseGlyph, &guestGlyph, &guestColor, &guestIterator);
        Require(found == FT_Get_Color_Glyph_Layer(native, baseGlyph, &nativeGlyph, &nativeColor, &nativeIterator));
        Require(guestGlyph == nativeGlyph && guestColor == nativeColor);
        Require(guestIterator.num_layers == nativeIterator.num_layers && guestIterator.layer == nativeIterator.layer);
        Require((guestIterator.p == nullptr) == (nativeIterator.p == nullptr));
    }
}

