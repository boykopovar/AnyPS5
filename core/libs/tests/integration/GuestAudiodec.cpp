struct Streams {
    AudiodecAuInfo au{sizeof(AudiodecAuInfo), nullptr, 0};
    AudiodecPcmItem pcm{sizeof(AudiodecPcmItem), nullptr, 0};
    std::vector<std::uint8_t> output = std::vector<std::uint8_t>(16384);
};

std::int32_t Decode(std::int32_t handle, AudiodecCtrl& ctrl, Streams& streams, const std::uint8_t* data, std::size_t size, std::uint32_t room = 16384) {
    streams.au.p_au_addr = const_cast<std::uint8_t*>(data);
    streams.au.ui_au_size = static_cast<std::uint32_t>(size);
    streams.pcm.p_pcm_addr = streams.output.data();
    streams.pcm.ui_pcm_size = room;
    ctrl.pAuInfo = &streams.au;
    ctrl.pPcmItem = &streams.pcm;
    return sceAudiodecDecode(handle, &ctrl);
}

int ZeroCrossings(const std::int16_t* samples, std::size_t count, std::size_t stride) {
    int crossings = 0;
    for (std::size_t i = stride; i < count * stride; i += stride) crossings += (samples[i - stride] < 0) != (samples[i] < 0);
    return crossings;
}

std::size_t AdtsLength(const std::uint8_t* frame) {
    return static_cast<std::size_t>((frame[3] & 3) << 11 | frame[4] << 3 | frame[5] >> 5);
}

