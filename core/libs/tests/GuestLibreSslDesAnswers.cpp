int main() {
    for (const auto& vector : vectors) {
        alignas(16) std::array<unsigned char, 160> schedule{};
        schedule.fill(0xa5);
        Require(DES_set_key_nid_postfix(vector.key.data(), schedule.data() + 16) == 0);
        Require(std::all_of(schedule.begin(), schedule.begin() + 16, [](auto byte) { return byte == 0xa5; }));
        Require(std::all_of(schedule.end() - 16, schedule.end(), [](auto byte) { return byte == 0xa5; }));
        const auto initialized = schedule;
        for (int repeat = 0; repeat < 3; ++repeat) {
            std::array<unsigned char, 10> output{};
            output.fill(0x5a);
            DES_ecb_encrypt_nid_postfix(vector.plain.data(), output.data() + 1, schedule.data() + 16, 1);
            Require(std::equal(vector.cipher.begin(), vector.cipher.end(), output.begin() + 1));
            DES_ecb_encrypt_nid_postfix(output.data() + 1, output.data() + 1, schedule.data() + 16, 0);
            Require(std::equal(vector.plain.begin(), vector.plain.end(), output.begin() + 1));
            Require(output.front() == 0x5a && output.back() == 0x5a);
            Require(schedule == initialized && schedule.front() == 0xa5 && schedule.back() == 0xa5);
        }
    }
}
