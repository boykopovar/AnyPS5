static void* BuildKey() {
    auto* rsa = RSA_new_nid_postfix();
    Require(rsa != nullptr);
    rsa->n = BN_bin2bn_nid_postfix(kModulus, sizeof(kModulus), nullptr);
    rsa->e = BN_bin2bn_nid_postfix(kExponent, sizeof(kExponent), nullptr);
    Require(rsa->n != nullptr && rsa->e != nullptr);
    void* pkey = EVP_PKEY_new_nid_postfix();
    Require(pkey != nullptr);
    Require(EVP_PKEY_set1_RSA_nid_postfix(pkey, rsa) == 1);
    RSA_free_nid_postfix(rsa);
    return pkey;
}

static int VerifyPss(void* pkey, const unsigned char* message, std::size_t messageLength,
                     const unsigned char* signature, std::size_t signatureLength, int saltLength) {
    auto* context = EVP_MD_CTX_create_nid_postfix();
    Require(context != nullptr);
    void* pctx = nullptr;
    Require(EVP_DigestVerifyInit_nid_postfix(context, &pctx, EVP_sha256_nid_postfix(), nullptr, pkey) == 1);
    auto* keyContext = static_cast<PkeyContext*>(pctx);
    Require(PkeyContextControl_nid_no_patch(keyContext, -1, -1, ControlPadding, PaddingPss, nullptr) == 1);
    Require(PkeyContextControl_nid_no_patch(keyContext, -1, -1, ControlPssSaltLen, saltLength, nullptr) == 1);
    int readPadding = 0;
    int readSalt = 0;
    Require(PkeyContextControl_nid_no_patch(keyContext, -1, -1, ControlGetPadding, 0, &readPadding) == 1 && readPadding == PaddingPss);
    Require(PkeyContextControl_nid_no_patch(keyContext, -1, -1, ControlGetPssSaltLen, 0, &readSalt) == 1 && readSalt == saltLength);
    Require(EVP_DigestUpdate_nid_postfix(context, message, messageLength) == 1);
    return EVP_DigestVerifyFinal_nid_postfix(context, const_cast<unsigned char*>(signature), signatureLength);
}

static void TestControlValidation(void* pkey) {
    auto* context = EVP_MD_CTX_create_nid_postfix();
    Require(context != nullptr);
    void* pctx = nullptr;
    Require(EVP_DigestVerifyInit_nid_postfix(context, &pctx, EVP_sha256_nid_postfix(), nullptr, pkey) == 1);
    auto* keyContext = static_cast<PkeyContext*>(pctx);

    int readSalt = 0;
    Require(PkeyContextControl_nid_no_patch(keyContext, -1, -1, ControlPssSaltLen, 32, nullptr) == -2);
    Require(PkeyContextControl_nid_no_patch(keyContext, -1, -1, ControlGetPssSaltLen, 0, &readSalt) == -2);
    Require(PkeyContextControl_nid_no_patch(keyContext, -1, -1, ControlPadding, PaddingPss, nullptr) == 1);
    Require(PkeyContextControl_nid_no_patch(keyContext, -1, -1, ControlPssSaltLen, -3, nullptr) == -2);
    Require(PkeyContextControl_nid_no_patch(keyContext, -1, -1, ControlPssSaltLen, 32, nullptr) == 1);
    Require(PkeyContextControl_nid_no_patch(keyContext, -1, -1, ControlMd, 0, const_cast<EvpMd*>(EVP_sha256_nid_postfix())) == 1);

    auto* dup = PkeyContextDuplicate_nid_no_patch(keyContext);
    Require(dup != nullptr);
    int dupPadding = 0;
    int dupSalt = 0;
    Require(PkeyContextControl_nid_no_patch(dup, -1, -1, ControlGetPadding, 0, &dupPadding) == 1 && dupPadding == PaddingPss);
    Require(PkeyContextControl_nid_no_patch(dup, -1, -1, ControlGetPssSaltLen, 0, &dupSalt) == 1 && dupSalt == 32);
    PkeyContextFree_nid_no_patch(dup);
}

int main() {
    void* const api[10] {};
    ApplicationHeapRegister_nid_no_patch(api);

    void* pkey = BuildKey();

    Require(VerifyPss(pkey, kMessage, sizeof(kMessage), kSignature, sizeof(kSignature), SaltLength) == 1);
    Require(VerifyPss(pkey, kMessage, sizeof(kMessage), kSignature, sizeof(kSignature), -2) == 1);

    std::vector<unsigned char> tampered(kSignature, kSignature + sizeof(kSignature));
    tampered[200] ^= 0x01;
    Require(VerifyPss(pkey, kMessage, sizeof(kMessage), tampered.data(), tampered.size(), SaltLength) != 1);

    std::vector<unsigned char> otherMessage(kMessage, kMessage + sizeof(kMessage));
    otherMessage[0] ^= 0x01;
    Require(VerifyPss(pkey, otherMessage.data(), otherMessage.size(), kSignature, sizeof(kSignature), SaltLength) != 1);

    Require(VerifyPss(pkey, kMessage, sizeof(kMessage), kSignature, sizeof(kSignature), SaltLength + 1) != 1);

    TestControlValidation(pkey);

    EVP_PKEY_free_nid_postfix(pkey);
    return 0;
}
