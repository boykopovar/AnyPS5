using Bytes = std::vector<std::uint8_t>;

struct Bits {
    Bytes bytes;
    unsigned count = 0;
    void Put(unsigned value, unsigned width) {
        for (unsigned bit = width; bit > 0; --bit, ++count) {
            if (count % 8 == 0) bytes.push_back(0);
            bytes.back() |= ((value >> (bit - 1)) & 1) << (7 - count % 8);
        }
    }
    void Align() {
        while (count % 8) Put(0, 1);
    }
};

struct Layout {
    unsigned channels;
    unsigned tag = 0;
    bool optional = false;
    unsigned falseSyncType = 0;
};

void PutPce(Bits& bits, Layout layout) {
    bits.Put(0, 4);
    bits.Put(1, 2);
    bits.Put(6, 4);
    bits.Put(1, 4);
    bits.Put(0, 4);
    bits.Put(0, 4);
    bits.Put(0, 2);
    bits.Put(0, 3);
    bits.Put(0, 4);
    const bool monoMixdown = layout.optional && layout.channels == 1;
    const bool stereoMixdown = layout.optional && layout.channels == 2;
    bits.Put(monoMixdown, 1);
    if (monoMixdown) bits.Put(layout.tag, 4);
    bits.Put(stereoMixdown, 1);
    if (stereoMixdown) bits.Put(layout.tag, 4);
    bits.Put(0, 1);
    bits.Put(layout.channels == 2, 1);
    bits.Put(layout.tag, 4);
    bits.Align();
    bits.Put(layout.falseSyncType ? 4 : layout.optional ? 3 : 0, 8);
    if (layout.falseSyncType) {
        bits.Put(0x2b7, 11);
        bits.Put(layout.falseSyncType, 5);
        bits.Put(1, 1);
        bits.Put(3, 4);
        bits.Put(0x548, 11);
    } else if (layout.optional) {
        bits.Put('p', 8);
        bits.Put('c', 8);
        bits.Put('e', 8);
    }
}

std::vector<Bytes> Frames(const std::uint8_t* data, std::size_t size) {
    std::vector<Bytes> frames;
    for (std::size_t offset = 0; offset < size;) {
        Require(offset + 7 <= size);
        const std::size_t length = (data[offset + 3] & 3) << 11 | data[offset + 4] << 3 | data[offset + 5] >> 5;
        Require(length > 7 && offset + length <= size);
        frames.emplace_back(data + offset, data + offset + length);
        offset += length;
    }
    return frames;
}

Bytes Payload(const Bytes& frame, Layout layout) {
    Bytes payload(frame.begin() + 7, frame.end());
    Require(payload.front() >> 5 == (layout.channels == 2 ? 1 : 0));
    payload.front() = (payload.front() & 0xe1) | (layout.tag << 1);
    return payload;
}

Bytes WithPce(const Bytes& frame, Layout layout, bool present) {
    Bytes result(frame.begin(), frame.begin() + 7);
    result[2] &= 0xfe;
    result[3] &= 0x3f;
    if (present) {
        Bits pce;
        pce.Put(5, 3);
        PutPce(pce, layout);
        result.insert(result.end(), pce.bytes.begin(), pce.bytes.end());
    }
    const auto payload = Payload(frame, layout);
    result.insert(result.end(), payload.begin(), payload.end());
    result[3] = (result[3] & 0xfc) | (result.size() >> 11);
    result[4] = result.size() >> 3;
    result[5] = (result[5] & 31) | ((result.size() & 7) << 5);
    return result;
}

class Oracle {
public:
    Oracle(Layout layout, bool he, bool pce) : channels(layout.channels), samples(he ? 2048 : 1024), rate(he ? 48000 : 24000) {
        Bits config;
        config.Put(2, 5);
        config.Put(6, 4);
        config.Put(pce ? 0 : channels, 4);
        config.Put(0, 3);
        if (pce) PutPce(config, layout);
        config.Put(0x2b7, 11);
        config.Put(5, 5);
        config.Put(he, 1);
        if (he) {
            config.Put(3, 4);
            config.Put(0x548, 11);
            config.Put(0, 1);
        }
        const AVCodec* codec = avcodec_find_decoder(AV_CODEC_ID_AAC);
        Require(codec);
        context = avcodec_alloc_context3(codec);
        Require(context);
        context->extradata = static_cast<std::uint8_t*>(av_mallocz(config.bytes.size() + AV_INPUT_BUFFER_PADDING_SIZE));
        Require(context->extradata);
        std::memcpy(context->extradata, config.bytes.data(), config.bytes.size());
        context->extradata_size = static_cast<int>(config.bytes.size());
        Require(avcodec_open2(context, codec, nullptr) == 0);
    }
    ~Oracle() { avcodec_free_context(&context); }
    Oracle(const Oracle&) = delete;
    Oracle& operator=(const Oracle&) = delete;
    Bytes Decode(const Bytes& payload) {
        AVPacket* packet = av_packet_alloc();
        AVFrame* frame = av_frame_alloc();
        Require(packet && frame);
        Require(av_new_packet(packet, static_cast<int>(payload.size())) == 0);
        std::memcpy(packet->data, payload.data(), payload.size());
        Require(avcodec_send_packet(context, packet) == 0);
        Require(avcodec_receive_frame(context, frame) == 0);
        Require(frame->format == AV_SAMPLE_FMT_FLTP);
        Require(frame->ch_layout.nb_channels == static_cast<int>(channels) && frame->nb_samples == static_cast<int>(samples) && frame->sample_rate == static_cast<int>(rate));
        Bytes pcm(samples * channels * sizeof(std::int16_t));
        for (unsigned sample = 0; sample < samples; ++sample) {
            for (unsigned channel = 0; channel < channels; ++channel) {
                const float value = reinterpret_cast<const float*>(frame->extended_data[channel])[sample];
                const auto converted = static_cast<std::int16_t>(std::clamp(std::lrint(static_cast<double>(value) * 32768), -32768L, 32767L));
                std::memcpy(pcm.data() + (sample * channels + channel) * sizeof(converted), &converted, sizeof(converted));
            }
        }
        av_frame_unref(frame);
        Require(avcodec_receive_frame(context, frame) == AVERROR(EAGAIN));
        av_frame_free(&frame);
        av_packet_free(&packet);
        return pcm;
    }
private:
    AVCodecContext* context = nullptr;
    unsigned channels;
    unsigned samples;
    unsigned rate;
};

