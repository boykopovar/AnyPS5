int main() {
    try {
        const auto device = OpenVulkanTestDevice();
        if (!device) return VulkanTestSkipped;
        GuestBlock guest;
        const auto shader = Compile(*device, guest);
        for (const auto& test : Cases) {
            Run(*device, shader, guest, test.records, test.word3);
            for (std::uint32_t lane = 0; lane < Lanes; ++lane) {
                for (std::uint32_t index = 0; index < Results; ++index) {
                    const auto actual = guest.Output()[lane * OutputStride + index];
                    const auto expected = test.expected[lane * Results + index];
                    Require(actual == expected, "gpu buffer format: format " + std::to_string((test.word3 >> 12u) & 0x7fu) + " word3 " + Hex(test.word3) + " records " + std::to_string(test.records) + " lane " + std::to_string(lane) + " " + Names[index] + " is " + Hex(actual) + ", expected " + Hex(expected));
                }
            }
        }
        for (const auto word3 : InvalidFormats) {
            Run(*device, shader, guest, 32u, word3);
            const auto output = guest.Output();
            Require(std::all_of(output.begin(), output.end(), [](std::uint32_t word) { return word == Untouched; }), "gpu buffer format: format " + std::to_string((word3 >> 12u) & 0x7fu) + " did not stop the invocation before its stores");
        }
        std::puts("gpu buffer format tests passed");
        return 0;
    } catch (const std::exception& error) {
        std::cerr << error.what() << '\n';
        return 1;
    }
}
