int main() {
    try {
        const auto device = OpenVulkanTestDevice();
        if (!device) return VulkanTestSkipped;
        const auto target = device->Target();
        std::vector<std::uint32_t> withoutFloat16;
        std::ranges::copy_if(target.supportedCapabilities, std::back_inserter(withoutFloat16), [](std::uint32_t capability) { return capability != spv::CapabilityFloat16; });
        auto emulatedTarget = target;
        emulatedTarget.supportedCapabilities = withoutFloat16;
        const Mode modes[] = {
            {"with f16 denormals kept, IEEE mode off", ShaderRecompiler::ShaderFloatMode{0xc0u, false, false, false}},
            {"with f16 denormals kept, IEEE mode on", ShaderRecompiler::ShaderFloatMode{0xc0u, false, true, false}},
            {"with f16 denormals kept, IEEE mode off, DX10 clamp", ShaderRecompiler::ShaderFloatMode{0xc0u, true, false, false}},
            {"with f16 denormals kept, IEEE mode on, DX10 clamp", ShaderRecompiler::ShaderFloatMode{0xc0u, true, true, false}},
            {"with f16 denormals flushed, IEEE mode off", ShaderRecompiler::ShaderFloatMode{0x00u, false, false, false}},
            {"with f16 denormals flushed, IEEE mode on", ShaderRecompiler::ShaderFloatMode{0x00u, false, true, false}},
            {"with f16 denormals flushed, IEEE mode off, DX10 clamp", ShaderRecompiler::ShaderFloatMode{0x00u, true, false, false}},
            {"with f16 denormals flushed, IEEE mode on, DX10 clamp", ShaderRecompiler::ShaderFloatMode{0x00u, true, true, false}},
        };
        for (const Mode& mode : modes) {
            Run(*device, target, mode);
            Check("device", mode);
            Run(*device, emulatedTarget, mode);
            Check("emulated f16", mode);
        }
        std::puts("f16 NaN source tests passed");
        return 0;
    } catch (const std::exception& error) {
        std::cerr << error.what() << '\n';
        return 1;
    }
}
