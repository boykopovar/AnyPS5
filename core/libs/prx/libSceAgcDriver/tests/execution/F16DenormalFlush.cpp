int main() {
    try {
        const auto device = OpenVulkanTestDevice();
        if (!device) return VulkanTestSkipped;
        for (std::uint32_t index = 0; index < CaseCount; ++index) {
            Shaders[index].words = {0x34020084u, 0x34040082u, 0xe0381000u, 0x80000401u, 0xbf8c3f70u, 0x7e1402ffu, 0x5a5a5a5au, Cases[index].word,
                                    0xe0701000u, 0x80010a02u, 0xbf810000u};
            for (std::uint32_t denorm16 = 0u; denorm16 < 4u; ++denorm16) {
                for (const bool ieee : {false, true}) {
                    Run(*device, Cases[index], Shaders[index], denorm16, ieee);
                    Check(Cases[index], denorm16, ieee);
                }
            }
        }
        std::puts("f16 denormal flush tests passed");
        return 0;
    } catch (const std::exception& error) {
        std::cerr << error.what() << '\n';
        return 1;
    }
}
