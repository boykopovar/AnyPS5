struct Row {
    std::uint32_t initial;
    std::uint32_t source;
    std::uint32_t comparator;
};

Row InputRow(std::uint32_t row) {
    const auto initial = Values[row % (Values.size() * Values.size()) / Values.size()];
    const auto source = Values[row % Values.size()];
    return {initial, source, row < Values.size() * Values.size() ? source : initial};
}

std::array<std::uint32_t, Checked> ExpectedRow(std::uint32_t row) {
    const auto input = InputRow(row);
    const auto* measured = &Expected[row * 3u];
    return {input.initial, measured[0], input.initial, measured[1], input.initial, measured[2], input.source, measured[0]};
}

std::array<std::uint32_t, 4> BufferDescriptor(const void* data, std::uint32_t bytes) {
    const auto address = reinterpret_cast<std::uintptr_t>(data);
    return {static_cast<std::uint32_t>(address), static_cast<std::uint32_t>((address >> 32u) & 0xffffu), bytes, 0x01016facu};
}

std::array<std::uint32_t, 8> TextureDescriptor(const void* data, std::uint32_t format) {
    const auto address = static_cast<std::uint64_t>(reinterpret_cast<std::uintptr_t>(data));
    return {
        static_cast<std::uint32_t>(address >> 8u),
        static_cast<std::uint32_t>((address >> 40u) & 0xffu) | (format << 20u) | (((TextureWidth - 1u) & 3u) << 30u),
        ((TextureWidth - 1u) >> 2u) | ((TextureHeight - 1u) << 14u),
        0xfacu | (Type2D << 28u),
        0u, 0u, 0u, 0u,
    };
}

ShaderRecompiler::RecompileResult Compile(std::uint32_t waveSize, const ShaderRecompiler::SpirvTarget& target, std::uint32_t format) {
    const std::span<const std::uint32_t> code(Code);
    std::vector<std::uint32_t> userData(16, 0u);
    const auto buffer = BufferDescriptor(Buffer.data(), static_cast<std::uint32_t>(Buffer.size() * 4u));
    const auto texture = TextureDescriptor(Texels.data(), format);
    std::copy(buffer.begin(), buffer.end(), userData.begin());
    std::copy(texture.begin(), texture.end(), userData.begin() + 4);
    const std::array<ShaderRecompiler::MemoryRegion, 1> memory{{{reinterpret_cast<std::uintptr_t>(code.data()), std::as_bytes(code)}}};
    const ShaderRecompiler::ShaderComputeStageInfo compute{{waveSize, 1, 1}, 0u, {false, false, false}, false, 1};
    ShaderRecompiler::RecompileRequest request{
        {ShaderStage::Compute, reinterpret_cast<std::uintptr_t>(code.data()), code, 0, {}},
        {waveSize, 0, userData, compute, std::nullopt, std::nullopt, memory},
        target,
        {0, 0, 0, 128}
    };
    request.useCache = false;
    return ShaderRecompiler::Recompile(request);
}

void Run(AgcDriver::VulkanDevice& device, std::uint32_t waveSize, const ShaderRecompiler::SpirvTarget& target, const char* name, std::uint32_t format) {
    const std::span<const std::uint32_t> code(Code);
    const auto result = Compile(waveSize, target, format);
    Texels.fill(0xdeadbeefu);
    for (std::uint32_t first = 0; first < Rows; first += waveSize) {
        Buffer.fill(0xdeadbeefu);
        for (std::uint32_t lane = 0; lane < waveSize; ++lane) {
            const auto input = InputRow((first + lane) % Rows);
            Buffer[lane * Inputs] = input.initial;
            Buffer[lane * Inputs + 1u] = input.source;
            Buffer[lane * Inputs + 2u] = input.comparator;
            Buffer[lane * Inputs + 3u] = 0u;
        }
        device.Dispatch(result, 1, 1, 1, {}, reinterpret_cast<std::uintptr_t>(code.data()));
        device.WaitIdle();
        constexpr std::array<const char*, Checked> names{"fmin returned", "fmin texel", "fmax returned", "fmax texel", "fcmpswap returned", "fcmpswap texel", "fmin without glc vdata", "fmin without glc texel"};
        for (std::uint32_t lane = 0; lane < waveSize; ++lane) {
            const auto row = (first + lane) % Rows;
            const auto expected = ExpectedRow(row);
            for (std::uint32_t j = 0; j < Checked; ++j) {
                const auto actual = Buffer[MaxLanes * Inputs + lane * Results + j];
                char message[192];
                std::snprintf(message, sizeof(message), "image float atomics %s, format %u: row %u %s is 0x%08x, expected 0x%08x", name, format, row, names[j], actual, expected[j]);
                Require(actual == expected[j], message);
            }
        }
    }
}

