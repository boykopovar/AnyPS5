int main() {
    try {
        const auto device = OpenVulkanTestDevice();
        if (!device) return VulkanTestSkipped;
        Run(*device, std::nullopt);
        Check(ExpectedInfinity, "no float mode");
        Run(*device, ShaderRecompiler::ShaderFloatMode{0xc0u, true, false, false});
        Check(ExpectedInfinity, "FP16_OVFL=0");
        Run(*device, ShaderRecompiler::ShaderFloatMode{0xc0u, true, false, true});
        Check(ExpectedOverflow, "FP16_OVFL=1");
        std::puts("fp16 overflow tests passed");
        return 0;
    } catch (const std::exception& error) {
        std::cerr << error.what() << '\n';
        return 1;
    }
}
