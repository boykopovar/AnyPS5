std::span<const KeyboardGlyphEntry> KeyboardGlyphTable() {
    return KeyboardGlyphs;
}

bool KeyboardHasGlyph(char32_t code) {
    if (code > 0xFFFF) return false;
    const auto found = std::lower_bound(KeyboardGlyphs.begin(), KeyboardGlyphs.end(), static_cast<char16_t>(code), [](const KeyboardGlyphEntry& entry, char16_t value) { return entry.code < value; });
    return found != KeyboardGlyphs.end() && found->code == code;
}

const KeyboardGlyphRows& KeyboardGlyph(char32_t code) {
    const auto lookup = KeyboardHasGlyph(code) ? code : KeyboardFallbackCode;
    const auto found = std::lower_bound(KeyboardGlyphs.begin(), KeyboardGlyphs.end(), static_cast<char16_t>(lookup), [](const KeyboardGlyphEntry& entry, char16_t value) { return entry.code < value; });
    return found->rows;
}

const KeyboardGlyphRows& KeyboardSymbolGlyph(ImeKeySymbol symbol) {
    Graphics::Require(symbol != ImeKeySymbol::None && static_cast<std::size_t>(symbol) <= KeyboardSymbolGlyphs.size(), "the system keyboard has no glyph for this key symbol");
    return KeyboardSymbolGlyphs[static_cast<std::size_t>(symbol) - 1];
}

std::int32_t KeyboardPanelWidth(const ImeKeyboardView& view) {
    return gridWidth(view) + 2 * KeyboardMetrics::Padding;
}

std::int32_t KeyboardPanelHeight(const ImeKeyboardView& view) {
    return gridTop() + gridHeight(view) + KeyboardMetrics::Padding;
}

std::int32_t KeyboardScale(VkExtent2D extent, const ImeKeyboardView& view) {
    auto scale = std::max<std::int32_t>(1, static_cast<std::int32_t>(extent.height / KeyboardMetrics::LinesPerScale));
    const auto width = static_cast<std::int64_t>(extent.width);
    const auto half = static_cast<std::int64_t>(extent.height - extent.height / 2);
    while (scale > 1 && (static_cast<std::int64_t>(KeyboardPanelWidth(view)) * scale > width || static_cast<std::int64_t>(KeyboardPanelHeight(view)) * scale > half)) --scale;
    return scale;
}

OverlayLayout LayOutKeyboard(const ImeKeyboardView& view, VkExtent2D extent) {
    Graphics::Require(extent.width != 0 && extent.height != 0, "the system keyboard needs a destination");
    Graphics::Require(view.rows != 0 && view.columns != 0, "the system keyboard needs at least one row and one column");
    Graphics::Require(view.caret <= view.text.size(), "the system keyboard caret is past its text");
    OverlayLayout layout;
    const auto scale = KeyboardScale(extent, view);
    layout.scale = scale;
    const auto width = KeyboardPanelWidth(view);
    const auto height = KeyboardPanelHeight(view);
    const auto screenWidth = static_cast<std::int32_t>(extent.width);
    const auto screenHeight = static_cast<std::int32_t>(extent.height);
    const auto half = screenHeight - screenHeight / 2;
    const auto left = std::max(0, (screenWidth - width * scale) / 2);
    const auto top = height * scale <= half ? screenHeight / 2 + (half - height * scale) / 2 : std::max(0, screenHeight - height * scale);
    layout.bounds = {left, top, width * scale, height * scale, static_cast<std::uint32_t>(OverlayColor::Panel)};
    layout.rects.push_back(layout.bounds);
    const auto rect = [&](std::int32_t x, std::int32_t y, std::int32_t w, std::int32_t h, OverlayColor color) {
        layout.rects.push_back({left + x * scale, top + y * scale, w * scale, h * scale, static_cast<std::uint32_t>(color)});
    };
    const auto inner = gridWidth(view);
    rect(KeyboardMetrics::Padding, KeyboardMetrics::Padding, inner, KeyboardMetrics::FieldHeight, OverlayColor::Field);
    std::size_t caret = 0;
    const auto characters = decode(view.text, view.caret, &caret);
    const auto textLeft = KeyboardMetrics::Padding + KeyboardMetrics::FieldInset;
    const auto textTop = KeyboardMetrics::Padding + KeyboardMetrics::FieldInset;
    const auto visible = static_cast<std::size_t>((inner - 2 * KeyboardMetrics::FieldInset + 1) / KeyboardMetrics::Advance);
    const auto first = caret > visible ? caret - visible : 0;
    const auto last = std::min(characters.size(), first + visible);
    for (auto index = first; index < last; ++index) {
        const auto column = static_cast<std::int32_t>(index - first);
        glyph(layout, KeyboardGlyph(characters[index]), left + (textLeft + column * KeyboardMetrics::Advance) * scale, top + textTop * scale, scale, OverlayColor::Text);
    }
    rect(textLeft + static_cast<std::int32_t>(caret - first) * KeyboardMetrics::Advance - 1, KeyboardMetrics::Padding + 1, 1, KeyboardMetrics::FieldHeight - 2, OverlayColor::Accent);
    for (const auto& key : view.keys) {
        Graphics::Require(key.columnSpan != 0 && key.rowSpan != 0 && key.column + key.columnSpan <= view.columns && key.row + key.rowSpan <= view.rows, "a system keyboard key lies outside its grid");
        const auto x = KeyboardMetrics::Padding + key.column * (KeyboardMetrics::KeyWidth + KeyboardMetrics::Gap);
        const auto y = gridTop() + key.row * (KeyboardMetrics::KeyHeight + KeyboardMetrics::Gap);
        const auto w = key.columnSpan * KeyboardMetrics::KeyWidth + (key.columnSpan - 1) * KeyboardMetrics::Gap;
        const auto h = key.rowSpan * KeyboardMetrics::KeyHeight + (key.rowSpan - 1) * KeyboardMetrics::Gap;
        if (key.selected) {
            rect(x, y, w, h, OverlayColor::Accent);
            rect(x + KeyboardMetrics::Border, y + KeyboardMetrics::Border, w - 2 * KeyboardMetrics::Border, h - 2 * KeyboardMetrics::Border, OverlayColor::Key);
        } else {
            rect(x, y, w, h, OverlayColor::Key);
        }
        const bool badge = !key.badge.empty();
        const auto block = badge ? 2 * KeyboardMetrics::GlyphHeight + KeyboardMetrics::LineGap : KeyboardMetrics::GlyphHeight;
        const auto labelTop = y + (h - block) / 2;
        if (key.symbol != ImeKeySymbol::None) {
            glyph(layout, KeyboardSymbolGlyph(key.symbol), left + (x + (w - KeyboardMetrics::GlyphWidth) / 2) * scale, top + labelTop * scale, scale, OverlayColor::Text);
        } else {
            line(layout, key.label, layout.bounds, x, w, labelTop, scale, OverlayColor::Text);
        }
        if (badge) line(layout, key.badge, layout.bounds, x, w, labelTop + KeyboardMetrics::GlyphHeight + KeyboardMetrics::LineGap, scale, OverlayColor::Graph);
    }
    return layout;
}

