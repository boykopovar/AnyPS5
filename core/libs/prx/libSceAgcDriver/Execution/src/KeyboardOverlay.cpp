std::int32_t gridWidth(const ImeKeyboardView& view) {
    return view.columns * KeyboardMetrics::KeyWidth + (view.columns - 1) * KeyboardMetrics::Gap;
}

std::int32_t gridHeight(const ImeKeyboardView& view) {
    return view.rows * KeyboardMetrics::KeyHeight + (view.rows - 1) * KeyboardMetrics::Gap;
}

std::int32_t gridTop() {
    return KeyboardMetrics::Padding * 2 + KeyboardMetrics::FieldHeight;
}

std::vector<char32_t> decode(const std::u16string& text, std::size_t caret, std::size_t* caretCharacter) {
    std::vector<char32_t> characters;
    characters.reserve(text.size());
    *caretCharacter = 0;
    for (std::size_t unit = 0; unit < text.size();) {
        if (unit < caret) *caretCharacter = characters.size() + 1;
        const char16_t first = text[unit];
        if (first >= 0xD800 && first <= 0xDBFF && unit + 1 < text.size() && text[unit + 1] >= 0xDC00 && text[unit + 1] <= 0xDFFF) {
            characters.push_back(0x10000 + ((static_cast<char32_t>(first) - 0xD800) << 10) + (static_cast<char32_t>(text[unit + 1]) - 0xDC00));
            unit += 2;
        } else {
            characters.push_back(first);
            ++unit;
        }
    }
    return characters;
}

void glyph(OverlayLayout& layout, const KeyboardGlyphRows& rows, std::int32_t left, std::int32_t top, std::int32_t scale, OverlayColor color) {
    for (std::int32_t y = 0; y < KeyboardMetrics::GlyphHeight; ++y) {
        const auto bits = rows[static_cast<std::size_t>(y)];
        std::int32_t x = 0;
        while (x < KeyboardMetrics::GlyphWidth) {
            if ((bits & (0x10u >> x)) == 0) {
                ++x;
                continue;
            }
            auto end = x;
            while (end < KeyboardMetrics::GlyphWidth && (bits & (0x10u >> end)) != 0) ++end;
            layout.rects.push_back({left + x * scale, top + y * scale, (end - x) * scale, scale, static_cast<std::uint32_t>(color)});
            x = end;
        }
    }
}

std::int32_t lineWidth(std::size_t characters) {
    return characters == 0 ? 0 : static_cast<std::int32_t>(characters) * KeyboardMetrics::Advance - 1;
}

void line(OverlayLayout& layout, const std::u16string& text, const OverlayRect& panel, std::int32_t x, std::int32_t width, std::int32_t y, std::int32_t scale, OverlayColor color) {
    std::size_t unused = 0;
    auto characters = decode(text, 0, &unused);
    const auto fits = static_cast<std::size_t>(std::max(0, width - 2 * KeyboardMetrics::Gap + 1) / KeyboardMetrics::Advance);
    characters.resize(std::min(characters.size(), fits));
    const auto start = x + (width - lineWidth(characters.size())) / 2;
    for (std::size_t index = 0; index < characters.size(); ++index) glyph(layout, KeyboardGlyph(characters[index]), panel.x + (start + static_cast<std::int32_t>(index) * KeyboardMetrics::Advance) * scale, panel.y + y * scale, scale, color);
}

