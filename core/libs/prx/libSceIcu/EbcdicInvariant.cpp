constexpr std::array<std::uint32_t, 4> InvariantChars{0xfffffbff, 0xffffffe5, 0x87fffffe, 0x87fffffe};
constexpr std::uint8_t AsciiQuestionMark = 0x3f;

bool Invariant(std::int32_t value) {
    return value <= 0x7f && (InvariantChars[value >> 5] & (1u << (value & 0x1f))) != 0;
}

std::int32_t Rank(std::uint8_t ebcdic) {
    if (ebcdic == 0) return 0;
    const std::int32_t ascii = AsciiFromEbcdic[ebcdic];
    return ascii == 0 || !Invariant(ascii) ? -static_cast<std::int32_t>(ebcdic) : ascii;
}

std::int32_t Length(const std::uint8_t* source, std::int32_t count) {
    if (count != -1) return count;
    std::int32_t length = 0;
    while (source[length] != 0) ++length;
    return length + 1;
}

