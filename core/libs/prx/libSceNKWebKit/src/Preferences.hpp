class Preferences final : public ObjectOf<ObjectType::Preferences> {
public:
    using StringValue = std::optional<std::u16string>;
    using Value = std::variant<std::monostate, bool, std::uint32_t, double, StringValue>;

    explicit Preferences(StringValue identifier = std::nullopt);
    Preferences(const Preferences& other);
    bool GetBool(std::u16string_view key) const;
    std::uint32_t GetUInt32(std::u16string_view key) const;
    double GetDouble(std::u16string_view key) const;
    StringValue GetString(std::u16string_view key) const;
    void Set(std::u16string_view key, Value value);
    void SetFeature(std::u16string_view key, bool value);
    void EnableAllExperimentalFeatures();
    void ResetAllInternalDebugFeatures();

private:
    const Value* findValue(std::u16string_view key, std::size_t type) const;
    StringValue identifier;
    std::map<std::u16string, Value, std::less<>> values;
    std::map<std::u16string, Value, std::less<>> overriddenDefaults;
};

