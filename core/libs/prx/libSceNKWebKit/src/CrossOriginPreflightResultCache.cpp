std::u16string Units(const StringImpl* impl) {
    const StringView view = NKWebKit::WtfAbi::ViewOf(impl);
    std::u16string text(view.length, u'\0');
    for (unsigned index = 0; index < view.length; ++index) text[index] = NKWebKit::WtfAbi::CodeUnitAt(view, index);
    return text;
}

std::u16string LowerASCII(std::u16string text) {
    for (char16_t& unit : text) {
        if (unit >= u'A' && unit <= u'Z') unit = static_cast<char16_t>(unit + (u'a' - u'A'));
    }
    return text;
}

StringView Literal(std::string_view text) {
    return {text.data(), static_cast<unsigned>(text.size()), true};
}

String MakeString(std::initializer_list<StringView> parts) {
    std::uint64_t total = 0;
    bool is8Bit = true;
    for (const auto& part : parts) {
        total += part.length;
        is8Bit = is8Bit && part.is8Bit;
    }
    if (total > static_cast<std::uint64_t>(std::numeric_limits<std::int32_t>::max()))
        throw std::length_error("WebCore::CrossOriginPreflightResultCacheItem message exceeds the maximum string length");
    void* characters = nullptr;
    String result(NKWebKit::WtfAbi::CreateUninitialized(static_cast<unsigned>(total), is8Bit, characters));
    std::size_t offset = 0;
    for (const auto& part : parts) {
        for (unsigned index = 0; index < part.length; ++index, ++offset) {
            const char16_t unit = NKWebKit::WtfAbi::CodeUnitAt(part, index);
            if (is8Bit) static_cast<unsigned char*>(characters)[offset] = static_cast<unsigned char>(unit);
            else static_cast<char16_t*>(characters)[offset] = unit;
        }
    }
    return result;
}

bool IsASCIIDigit(char16_t c) {
    return c >= u'0' && c <= u'9';
}

bool IsASCIIAlphanumeric(char16_t c) {
    return IsASCIIDigit(c) || (c >= u'a' && c <= u'z') || (c >= u'A' && c <= u'Z');
}

bool IsHTTPSpace(char16_t c) {
    return c == u' ' || c == u'\n' || c == u'\t' || c == u'\r';
}

bool IsTokenCharacter(char16_t c) {
    return IsASCIIAlphanumeric(c) || (c && std::u16string_view(u"!#$%&'*+-.^_`|~").find(c) != std::u16string_view::npos);
}

bool IsDelimiter(char16_t c) {
    return c && std::u16string_view(u"(),/:;<=>?@[\\]{}\"").find(c) != std::u16string_view::npos;
}

bool IsValidHTTPToken(std::u16string_view value) {
    return std::all_of(value.begin(), value.end(), IsTokenCharacter);
}

bool IsSpaceOrNewline(char16_t c) {
    if (c <= 0xFF) return c == u' ' || (c <= 0xD && c >= 0x9);
    return u_charDirection_nid_postfix(c) == kWhiteSpaceNeutral;
}

std::optional<unsigned> ToUIntStrict(const String& value) {
    if (!value.impl) return std::nullopt;
    const std::u16string text = Units(value.impl);
    std::size_t index = 0;
    while (index < text.size() && IsSpaceOrNewline(text[index])) ++index;
    if (index < text.size() && text[index] == u'+') ++index;
    if (index == text.size() || !IsASCIIDigit(text[index])) return std::nullopt;
    constexpr unsigned maximum = std::numeric_limits<unsigned>::max();
    unsigned result = 0;
    while (index < text.size() && IsASCIIDigit(text[index])) {
        const unsigned digit = static_cast<unsigned>(text[index] - u'0');
        if (result > maximum / 10 || (result == maximum / 10 && digit > maximum % 10)) return std::nullopt;
        result = result * 10 + digit;
        ++index;
    }
    while (index < text.size() && IsSpaceOrNewline(text[index])) ++index;
    if (index != text.size()) return std::nullopt;
    return result;
}

bool AddToAllowList(const std::u16string& text, std::size_t start, std::size_t end, bool foldCase, std::set<std::u16string>& set) {
    while (start <= end && IsHTTPSpace(text[start])) ++start;
    if (start > end) return true;
    while (end && IsHTTPSpace(text[end])) --end;
    std::u16string token = text.substr(start, end - start + 1);
    if (!IsValidHTTPToken(token)) return false;
    set.insert(foldCase ? LowerASCII(std::move(token)) : std::move(token));
    return true;
}

std::optional<std::set<std::u16string>> ParseAllowList(const String& value, bool foldCase) {
    const std::u16string text = Units(value.impl);
    std::set<std::u16string> set;
    std::size_t start = 0;
    std::size_t end = 0;
    while ((end = text.find(u',', start)) != std::u16string::npos) {
        if (start != end && !AddToAllowList(text, start, end - 1, foldCase, set)) return std::nullopt;
        start = end + 1;
    }
    if (start != text.size() && !AddToAllowList(text, start, text.size() - 1, foldCase, set)) return std::nullopt;
    return set;
}

bool IsValidAcceptHeaderValue(std::u16string_view value) {
    for (const char16_t c : value) {
        if (IsASCIIAlphanumeric(c) || c == u',' || c == u'/' || c == u';' || c == u'=') continue;
        if (c == 0x7F || (c < 0x20 && c != u'\t')) return false;
        if (IsDelimiter(c)) return false;
    }
    return true;
}

bool IsValidLanguageHeaderValue(std::u16string_view value) {
    for (const char16_t c : value) {
        if (IsASCIIAlphanumeric(c) || (c && std::u16string_view(u" *,-.;=").find(c) != std::u16string_view::npos)) continue;
        return false;
    }
    return true;
}

bool ContainsCORSUnsafeRequestHeaderBytes(std::u16string_view value) {
    for (const char16_t c : value) {
        if ((c < 0x20 && c != u'\t') || c == 0x7F || (c && std::u16string_view(u"\"():<>?@[\\]{}").find(c) != std::u16string_view::npos))
            return true;
    }
    return false;
}

bool IsFormContentType(std::u16string_view value) {
    while (!value.empty() && IsHTTPSpace(value.front())) value.remove_prefix(1);
    while (!value.empty() && IsHTTPSpace(value.back())) value.remove_suffix(1);
    const std::size_t slash = value.find(u'/');
    if (slash == std::u16string_view::npos) return false;
    const std::u16string_view type = value.substr(0, slash);
    std::u16string_view subtype = value.substr(slash + 1);
    subtype = subtype.substr(0, subtype.find(u';'));
    while (!subtype.empty() && subtype.back() == u' ') subtype.remove_suffix(1);
    const std::u16string mimeType = LowerASCII(std::u16string(type) + u'/' + std::u16string(subtype));
    return mimeType == u"application/x-www-form-urlencoded" || mimeType == u"multipart/form-data" || mimeType == u"text/plain";
}

bool IsCrossOriginSafeRequestHeader(HTTPHeaderName name, const String& header) {
    const std::u16string value = Units(header.impl);
    switch (name) {
    case HTTPHeaderName::Accept:
        if (!IsValidAcceptHeaderValue(value)) return false;
        break;
    case HTTPHeaderName::AcceptLanguage:
    case HTTPHeaderName::ContentLanguage:
        if (!IsValidLanguageHeaderValue(value)) return false;
        break;
    case HTTPHeaderName::ContentType:
        if (ContainsCORSUnsafeRequestHeaderBytes(value) || !IsFormContentType(value)) return false;
        break;
    default:
        return false;
    }
    return value.size() <= kMaxSafeHeaderValueLength;
}

template<class TEntry>
void Validate(const HeaderVector<TEntry>& vector) {
    if (vector.size > vector.capacity) throw std::invalid_argument("invalid WebCore::HTTPHeaderMap vector size");
    if (vector.size && !vector.buffer) throw std::invalid_argument("null WebCore::HTTPHeaderMap vector storage");
}

bool Contains(const std::set<std::u16string>& set, bool hasTable, const StringImpl* key, bool foldCase) {
    if (!hasTable) return false;
    if (!key) throw std::invalid_argument("null WTF::String looked up in a WebCore::CrossOriginPreflightResultCacheItem set");
    return set.contains(foldCase ? LowerASCII(Units(key)) : Units(key));
}

bool AllowsCrossOriginMethod(const Item& item, const String& method, StoredCredentialsPolicy storedCredentialsPolicy) {
    if (Contains(item.methods, item.hasMethodsTable, method.impl, false)) return true;
    if (item.methods.contains(u"*") && storedCredentialsPolicy != StoredCredentialsPolicy::Use) return true;
    const std::u16string text = Units(method.impl);
    return text == u"GET" || text == u"HEAD" || text == u"POST";
}

std::optional<String> ValidateCrossOriginHeaders(const Item& item, const HTTPHeaderMap& requestHeaders, StoredCredentialsPolicy storedCredentialsPolicy) {
    const bool validWildcard = item.headers.contains(u"*") && storedCredentialsPolicy != StoredCredentialsPolicy::Use;
    Validate(requestHeaders.common);
    Validate(requestHeaders.uncommon);
    for (unsigned index = 0; index < requestHeaders.common.size; ++index) {
        const auto& header = requestHeaders.common.buffer[index];
        const auto nameIndex = static_cast<std::size_t>(static_cast<std::uint32_t>(header.key));
        if (nameIndex >= NKWebKit::HttpAbi::headerNames.size()) throw std::invalid_argument("unknown WebCore::HTTPHeaderName in a WebCore::HTTPHeaderMap");
        if (IsCrossOriginSafeRequestHeader(header.key, header.value)) continue;
        const std::string_view name(NKWebKit::HttpAbi::headerNames[nameIndex]);
        if (!item.headers.contains(LowerASCII(std::u16string(name.begin(), name.end()))) && !validWildcard)
            return String(_ZN3WTF10StringImpl6createEPKhj(reinterpret_cast<const unsigned char*>(name.data()), static_cast<unsigned>(name.size())));
    }
    for (unsigned index = 0; index < requestHeaders.uncommon.size; ++index) {
        const auto& header = requestHeaders.uncommon.buffer[index];
        if (!Contains(item.headers, item.hasHeadersTable, header.key.impl, true) && !validWildcard) return String(header.key);
    }
    return std::nullopt;
}

bool AllowsRequest(const Item& item, StoredCredentialsPolicy storedCredentialsPolicy, const String& method, const HTTPHeaderMap& requestHeaders) {
    if (item.absoluteExpiryTime < _ZN3WTF13MonotonicTime3nowEv().m_value) return false;
    if (storedCredentialsPolicy == StoredCredentialsPolicy::Use && item.storedCredentialsPolicy == StoredCredentialsPolicy::DoNotUse) return false;
    if (!AllowsCrossOriginMethod(item, method, storedCredentialsPolicy)) return false;
    if (ValidateCrossOriginHeaders(item, requestHeaders, storedCredentialsPolicy)) return false;
    return true;
}

std::set<std::u16string> TakeSet(StringImpl** table, bool foldCase) {
    std::set<std::u16string> set;
    if (!table) return set;
    unsigned* metadata = reinterpret_cast<unsigned*>(table) - kHashTableMetadataFields;
    const unsigned tableSize = metadata[kHashTableSizeField];
    for (unsigned index = 0; index < tableSize; ++index) {
        StringImpl* entry = table[index];
        if (!entry || entry == reinterpret_cast<StringImpl*>(static_cast<std::intptr_t>(-1))) continue;
        set.insert(foldCase ? LowerASCII(Units(entry)) : Units(entry));
        NKWebKit::WtfAbi::Release(entry);
    }
    _ZN3WTF8fastFreeEPv(metadata);
    return set;
}

std::unique_ptr<Item> Adopt(CrossOriginPreflightResultCacheItem* guest) {
    if (!guest) return nullptr;
    auto item = std::make_unique<Item>();
    item->absoluteExpiryTime = guest->absoluteExpiryTime;
    item->storedCredentialsPolicy = guest->storedCredentialsPolicy;
    item->hasMethodsTable = guest->methods;
    item->methods = TakeSet(guest->methods, false);
    item->hasHeadersTable = guest->headers;
    item->headers = TakeSet(guest->headers, true);
    _ZN3WTF8fastFreeEPv(guest);
    return item;
}

