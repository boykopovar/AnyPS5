double NKWebKit::PreflightCache::LifetimeSeconds(const String& maxAge) {
    const std::optional<unsigned> seconds = ToUIntStrict(maxAge);
    if (!seconds) return kDefaultPreflightCacheTimeout;
    return std::min(static_cast<double>(*seconds), kMaxPreflightCacheTimeout);
}

Creation NKWebKit::PreflightCache::Create(StoredCredentialsPolicy storedCredentialsPolicy, const ResourceResponseBase& response) {
    const String allowMethods = _ZNK7WebCore20ResourceResponseBase15httpHeaderFieldENS_14HTTPHeaderNameE(&response, HTTPHeaderName::AccessControlAllowMethods);
    auto methods = ParseAllowList(allowMethods, false);
    if (!methods)
        return {nullptr, MakeString({Literal("Header Access-Control-Allow-Methods has an invalid value: "), NKWebKit::WtfAbi::ViewOf(allowMethods.impl)})};
    const String allowHeaders = _ZNK7WebCore20ResourceResponseBase15httpHeaderFieldENS_14HTTPHeaderNameE(&response, HTTPHeaderName::AccessControlAllowHeaders);
    auto headers = ParseAllowList(allowHeaders, true);
    if (!headers)
        return {nullptr, MakeString({Literal("Header Access-Control-Allow-Headers has an invalid value: "), NKWebKit::WtfAbi::ViewOf(allowHeaders.impl)})};
    const String maxAge = _ZNK7WebCore20ResourceResponseBase15httpHeaderFieldENS_14HTTPHeaderNameE(&response, HTTPHeaderName::AccessControlMaxAge);
    auto item = std::make_unique<Item>();
    item->absoluteExpiryTime = _ZN3WTF13MonotonicTime3nowEv().m_value + LifetimeSeconds(maxAge);
    item->storedCredentialsPolicy = storedCredentialsPolicy;
    item->hasMethodsTable = !methods->empty();
    item->methods = std::move(*methods);
    item->hasHeadersTable = !headers->empty();
    item->headers = std::move(*headers);
    return {std::move(item), String()};
}

std::optional<String> NKWebKit::PreflightCache::ValidateMethodAndHeaders(const Item& item, const String& method, const HTTPHeaderMap& requestHeaders) {
    if (!AllowsCrossOriginMethod(item, method, item.storedCredentialsPolicy))
        return MakeString({Literal("Method "), NKWebKit::WtfAbi::ViewOf(method.impl), Literal(" is not allowed by Access-Control-Allow-Methods.")});
    if (const auto badHeader = ValidateCrossOriginHeaders(item, requestHeaders, item.storedCredentialsPolicy))
        return MakeString({Literal("Request header field "), NKWebKit::WtfAbi::ViewOf(badHeader->impl), Literal(" is not allowed by Access-Control-Allow-Headers.")});
    return std::nullopt;
}

void NKWebKit::PreflightCache::Append(const String& origin, const URL& url, std::unique_ptr<Item> item) {
    if (!origin.impl) throw std::invalid_argument("null origin string for WebCore::CrossOriginPreflightResultCache");
    if (!url.impl) throw std::invalid_argument("null URL string for WebCore::CrossOriginPreflightResultCache");
    Cache& cache = State();
    cache.hasTable = true;
    cache.entries[Key{Units(origin.impl), Units(url.impl)}] = std::move(item);
}

