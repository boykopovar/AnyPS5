using Text = std::u16string;
using View = std::u16string_view;

struct Buffer {
    const char16_t* position;
    const char16_t* end;

    bool HasCharactersRemaining() const { return position < end; }
    bool AtEnd() const { return position == end; }
    std::size_t LengthRemaining() const { return static_cast<std::size_t>(end - position); }
};

Text Widen(std::string_view ascii) {
    Text text;
    text.reserve(ascii.size());
    for (const char unit : ascii) text.push_back(static_cast<char16_t>(static_cast<unsigned char>(unit)));
    return text;
}

Text Between(const char16_t* begin, const char16_t* end) {
    return Text(begin, static_cast<std::size_t>(end - begin));
}

bool IsASCIISpace(char16_t c) {
    return c <= u' ' && (c == u' ' || (c <= 0xD && c >= 0x9));
}

bool IsNotASCIISpace(char16_t c) {
    return !IsASCIISpace(c);
}

bool IsHTMLSpace(char16_t c) {
    return c <= u' ' && (c == u' ' || c == u'\n' || c == u'\t' || c == u'\r' || c == u'\f');
}

bool IsASCIIAlpha(char16_t c) {
    return (c | 0x20) >= u'a' && (c | 0x20) <= u'z';
}

bool IsASCIIDigit(char16_t c) {
    return c >= u'0' && c <= u'9';
}

bool IsASCIIAlphanumeric(char16_t c) {
    return IsASCIIDigit(c) || IsASCIIAlpha(c);
}

char16_t ToASCIILower(char16_t c) {
    return static_cast<char16_t>(c | ((c >= u'A' && c <= u'Z') << 5));
}

bool EqualIgnoringASCIICase(View text, std::string_view other) {
    if (text.size() != other.size()) return false;
    for (std::size_t index = 0; index < text.size(); ++index) {
        if (ToASCIILower(text[index]) != ToASCIILower(static_cast<char16_t>(static_cast<unsigned char>(other[index])))) return false;
    }
    return true;
}

bool EqualLettersIgnoringASCIICase(const char16_t* characters, std::string_view lowercaseLetters) {
    for (std::size_t index = 0; index < lowercaseLetters.size(); ++index) {
        if ((characters[index] | 0x20) != static_cast<unsigned char>(lowercaseLetters[index])) return false;
    }
    return true;
}

bool EqualLettersIgnoringASCIICase(View text, std::string_view lowercaseLetters) {
    return text.size() == lowercaseLetters.size() && EqualLettersIgnoringASCIICase(text.data(), lowercaseLetters);
}

bool SkipExactly(Buffer& buffer, char16_t delimiter) {
    if (buffer.HasCharactersRemaining() && *buffer.position == delimiter) {
        ++buffer.position;
        return true;
    }
    return false;
}

template <bool (*Predicate)(char16_t)>
bool SkipExactly(Buffer& buffer) {
    if (buffer.HasCharactersRemaining() && Predicate(*buffer.position)) {
        ++buffer.position;
        return true;
    }
    return false;
}

template <bool (*Predicate)(char16_t)>
void SkipWhile(Buffer& buffer) {
    while (buffer.HasCharactersRemaining() && Predicate(*buffer.position)) ++buffer.position;
}

void SkipUntil(Buffer& buffer, char16_t delimiter) {
    while (buffer.HasCharactersRemaining() && *buffer.position != delimiter) ++buffer.position;
}

bool SkipExactlyIgnoringASCIICase(Buffer& buffer, std::string_view literal) {
    if (buffer.LengthRemaining() < literal.size()) return false;
    if (!EqualLettersIgnoringASCIICase(buffer.position, literal)) return false;
    buffer.position += literal.size();
    return true;
}

constexpr int kNonAlphabet = -1;

int Base64Value(unsigned character, bool urlAlphabet) {
    if (character >= u'A' && character <= u'Z') return static_cast<int>(character - u'A');
    if (character >= u'a' && character <= u'z') return static_cast<int>(character - u'a') + 26;
    if (character >= u'0' && character <= u'9') return static_cast<int>(character - u'0') + 52;
    if (character == (urlAlphabet ? u'-' : u'+')) return 62;
    if (character == (urlAlphabet ? u'_' : u'/')) return 63;
    return kNonAlphabet;
}

bool Base64Decode(View data, std::vector<std::uint8_t>& out, bool validatePadding, bool urlAlphabet) {
    out.clear();
    const std::size_t length = data.size();
    if (!length) return true;
    out.resize(length);
    unsigned equalsSignCount = 0;
    std::size_t outLength = 0;
    bool hadError = false;
    for (std::size_t index = 0; index < length; ++index) {
        const unsigned character = data[index];
        if (character == u'=') {
            ++equalsSignCount;
            if (validatePadding && equalsSignCount > 2) {
                hadError = true;
                break;
            }
        } else {
            const int decoded = Base64Value(character, urlAlphabet);
            if (decoded == kNonAlphabet || equalsSignCount) {
                hadError = true;
                break;
            }
            out[outLength++] = static_cast<std::uint8_t>(decoded);
        }
    }
    if (outLength < out.size()) out.resize(outLength);
    if (hadError) return false;
    if (!outLength) return !equalsSignCount;
    if (validatePadding && equalsSignCount && (outLength + equalsSignCount) % 4) return false;
    if ((outLength % 4) == 1) return false;
    outLength -= (outLength + 3) / 4;
    if (!outLength) return false;
    std::size_t sourceIndex = 0;
    std::size_t destinationIndex = 0;
    if (outLength > 1) {
        while (destinationIndex < outLength - 2) {
            out[destinationIndex] = static_cast<std::uint8_t>(((out[sourceIndex] << 2) & 255) | ((out[sourceIndex + 1] >> 4) & 003));
            out[destinationIndex + 1] = static_cast<std::uint8_t>(((out[sourceIndex + 1] << 4) & 255) | ((out[sourceIndex + 2] >> 2) & 017));
            out[destinationIndex + 2] = static_cast<std::uint8_t>(((out[sourceIndex + 2] << 6) & 255) | (out[sourceIndex + 3] & 077));
            sourceIndex += 4;
            destinationIndex += 3;
        }
    }
    if (destinationIndex < outLength) out[destinationIndex] = static_cast<std::uint8_t>(((out[sourceIndex] << 2) & 255) | ((out[sourceIndex + 1] >> 4) & 003));
    if (++destinationIndex < outLength) out[destinationIndex] = static_cast<std::uint8_t>(((out[sourceIndex + 1] << 4) & 255) | ((out[sourceIndex + 2] >> 2) & 017));
    if (outLength < out.size()) out.resize(outLength);
    return true;
}

bool IsBase64OrBase64URLCharacter(char16_t c) {
    return IsASCIIAlphanumeric(c) || c == u'+' || c == u'/' || c == u'-' || c == u'_';
}

std::optional<unsigned> ParseHashAlgorithmAdvancingPosition(Buffer& buffer) {
    if (SkipExactlyIgnoringASCIICase(buffer, "sha256")) return kSha256;
    if (SkipExactlyIgnoringASCIICase(buffer, "sha384")) return kSha384;
    if (SkipExactlyIgnoringASCIICase(buffer, "sha512")) return kSha512;
    return std::nullopt;
}

std::optional<Digest> ParseCryptographicDigest(Buffer& buffer) {
    if (buffer.AtEnd()) return std::nullopt;
    const auto algorithm = ParseHashAlgorithmAdvancingPosition(buffer);
    if (!algorithm) return std::nullopt;
    if (!SkipExactly(buffer, u'-')) return std::nullopt;
    const char16_t* beginHashValue = buffer.position;
    SkipWhile<IsBase64OrBase64URLCharacter>(buffer);
    SkipExactly(buffer, u'=');
    SkipExactly(buffer, u'=');
    if (buffer.position == beginHashValue) return std::nullopt;
    Digest digest;
    digest.algorithm = *algorithm;
    const View hashValue(beginHashValue, static_cast<std::size_t>(buffer.position - beginHashValue));
    if (!Base64Decode(hashValue, digest.value, true, false)) {
        if (!Base64Decode(hashValue, digest.value, false, true)) return std::nullopt;
    }
    return digest;
}

