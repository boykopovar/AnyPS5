void ReportUnsupportedDirective(PolicyHost& host, const Text& name) {
    Text message;
    if (EqualLettersIgnoringASCIICase(name, "allow"))
        message = Widen("The 'allow' directive has been replaced with 'default-src'. Please use that directive instead, as 'allow' has no effect.");
    else if (EqualLettersIgnoringASCIICase(name, "options"))
        message = Widen("The 'options' directive has been replaced with 'unsafe-inline' and 'unsafe-eval' source expressions for the 'script-src' and 'style-src' directives. Please use those directives instead, as 'options' has no effect.");
    else if (EqualLettersIgnoringASCIICase(name, "policy-uri"))
        message = Widen("The 'policy-uri' directive has been removed from the specification. Please specify a complete policy via the Content-Security-Policy header.");
    else
        message = Widen("Unrecognized Content-Security-Policy directive '") + name + Widen("'.\n");
    host.LogToConsole(message);
}

void ReportDirectiveAsSourceExpression(PolicyHost& host, const Text& directiveName, const Text& sourceExpression) {
    host.LogToConsole(Widen("The Content Security Policy directive '") + directiveName + Widen("' contains '") + sourceExpression + Widen("' as a source expression. Did you mean '") + directiveName + Widen(" ...; ") + sourceExpression + Widen("...' (note the semicolon)?"));
}

void ReportDuplicateDirective(PolicyHost& host, const Text& name) {
    host.LogToConsole(Widen("Ignoring duplicate Content-Security-Policy directive '") + name + Widen("'.\n"));
}

