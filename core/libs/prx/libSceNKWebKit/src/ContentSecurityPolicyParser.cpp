void ReportInvalidPathCharacter(PolicyHost& host, const Text& directiveName, const Text& value, char16_t invalidCharacter) {
    Text ignoring;
    if (invalidCharacter == u'?')
        ignoring = Widen("The query component, including the '?', will be ignored.");
    else
        ignoring = Widen("The fragment identifier, including the '#', will be ignored.");
    host.LogToConsole(Widen("The source list for Content Security Policy directive '") + directiveName + Widen("' contains a source with an invalid path: '") + value + Widen("'. ") + ignoring);
}

void ReportInvalidSourceExpression(PolicyHost& host, const Text& directiveName, const Text& source) {
    Text message = Widen("The source list for Content Security Policy directive '") + directiveName + Widen("' contains an invalid source: '") + source + Widen("'. It will be ignored.");
    if (EqualLettersIgnoringASCIICase(source, "'none'")) message += Widen(" Note that 'none' has no effect unless it is the only expression in the source list.");
    host.LogToConsole(message);
}

