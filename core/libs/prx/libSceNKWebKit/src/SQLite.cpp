bool OpenDatabase(SQLiteDatabase& db, const String& filename, int openMode, const char* function) {
    static std::once_flag initialized;
    std::call_once(initialized, [] {
        if (sqlite3_initialize_nid_postfix() != SqliteOk) throw std::runtime_error("Failed to initialize SQLite");
    });
    Close(db);
    {
        std::lock_guard locker(isDatabaseOpeningForbiddenMutex);
        if (isDatabaseOpeningForbidden) {
            SetOpenErrorMessage(db, "opening database is forbidden");
            return false;
        }
        int flags = SqliteOpenAutoProxy;
        switch (openMode) {
        case OpenModeReadOnly:
            flags |= SqliteOpenReadOnly;
            break;
        case OpenModeReadWrite:
            flags |= SqliteOpenReadWrite;
            break;
        case OpenModeReadWriteCreate:
            flags |= SqliteOpenReadWrite | SqliteOpenCreate;
            break;
        }
        const CString path = Utf8(filename);
        db.openError = sqlite3_open_v2_nid_postfix(Bytes(path), &db.db, flags, nullptr);
        if (db.openError != SqliteOk) {
            SetOpenErrorMessage(db, db.db ? sqlite3_errmsg_nid_postfix(db.db) : "sqlite_open returned null");
            sqlite3_close_nid_postfix(db.db);
            db.db = nullptr;
            return false;
        }
    }
    OverrideUnauthorizedFunctions(db);
    db.openError = sqlite3_extended_result_codes_nid_postfix(db.db, 1);
    if (db.openError != SqliteOk) {
        SetOpenErrorMessage(db, sqlite3_errmsg_nid_postfix(db.db));
        sqlite3_close_nid_postfix(db.db);
        db.db = nullptr;
        return false;
    }
    {
        TransactionInProgressAutoCounter transactionCounter;
        ExecuteCommand(db, Concatenate(u"PRAGMA temp_store = MEMORY;"), function);
    }
    if (openMode != OpenModeReadOnly) UseWALJournalMode(db, function);
    return db.db != nullptr;
}

