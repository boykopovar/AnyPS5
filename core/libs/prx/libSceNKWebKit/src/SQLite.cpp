StringView View(const StringImpl* impl) {
    if (!impl) return {nullptr, 0, true};
    return {impl->data, impl->length, (impl->hashAndFlags & 4) != 0};
}

char16_t Unit(const StringView& view, unsigned index) {
    if (view.is8Bit) return static_cast<const unsigned char*>(view.data)[index];
    return static_cast<const char16_t*>(view.data)[index];
}

