OriginRef CreateFromURL(const URL& url, const char* caller) {
    if (ProtocolIs(url, "blob")) NotImplemented_nid_no_patch(caller);
    PendingOrigin origin;
    if (ShouldTreatAsOpaqueOrigin(url)) {
        InitializeOpaque(*origin);
        return origin.Release();
    }
    const auto protocol = _ZNK3WTF3URL8protocolEv(&url);
    const auto host = _ZNK3WTF3URL4hostEv(&url);
    const auto port = NKWebKit::WtfAbi::PortOf(url);
    if (!url.impl) SetTuple(origin->data, String(), String(), {0, false});
    else if (!protocol.length && !host.length && !port) SetOpaque(origin->data, GenerateOpaqueOriginIdentifier());
    else SetTuple(origin->data, LowercaseOrEmpty(protocol), LowercaseOrEmpty(host), {port.value_or(0), port.has_value()});
    InitializeShared(*origin);
    if (origin->canLoadLocalResources) origin->filePath = _ZNK3WTF3URL14fileSystemPathEv(&url);
    return origin.Release();
}

String DataToString(const SecurityOriginData& data) {
    const auto& protocol = Protocol(data);
    if (EqualsLiteral(protocol, "file", false)) return Concatenate({Literal("file://")});
    const auto& host = Host(data);
    if (IsEmpty(protocol) && IsEmpty(host)) return String();
    const auto port = Port(data);
    if (!port.hasValue) return Concatenate({ViewOf(protocol), Literal("://"), ViewOf(host)});
    const auto digits = std::to_string(port.value);
    return Concatenate({ViewOf(protocol), Literal("://"), ViewOf(host), Literal(":"), Literal(digits.c_str())});
}

OriginRef CreateFromData(const SecurityOriginData& data, const char* caller) {
    PendingOrigin origin;
    IsolatedCopyData(origin->data, data);
    InitializeShared(*origin);
    if (origin->canLoadLocalResources) {
        if (!EqualsLiteral(Protocol(origin->data), "file", false)) NotImplemented_nid_no_patch(caller);
        origin->filePath = Concatenate({Literal("/")});
    }
    return origin.Release();
}

bool PassesFileCheck(const SecurityOrigin& origin, const SecurityOrigin& other) {
    return !origin.enforcesFilePathSeparation && !other.enforcesFilePathSeparation;
}

bool IsSameSchemeHostPort(const SecurityOrigin& origin, const SecurityOrigin& other) {
    if (!EqualData(origin.data, other.data)) return false;
    if (origin.isLocal && !PassesFileCheck(origin, other)) return false;
    return true;
}

bool EndsWith(const StringView& view, const StringView& suffix) {
    if (suffix.length > view.length) return false;
    const unsigned offset = view.length - suffix.length;
    for (unsigned i = 0; i < suffix.length; ++i) {
        if (NKWebKit::WtfAbi::CodeUnitAt(view, offset + i) != NKWebKit::WtfAbi::CodeUnitAt(suffix, i)) return false;
    }
    return true;
}

bool MatchesOriginAccessEntry(const SecurityOrigin& origin, const String& domainSuffix, bool treatIPAddressAsDomain) {
    const auto entryProtocol = _ZNK3WTF6String23convertToASCIILowercaseEv(&Protocol(origin.data));
    const auto entryHost = _ZNK3WTF6String23convertToASCIILowercaseEv(&domainSuffix);
    const auto entryHostView = ViewOf(entryHost);
    const bool entryHostIsIPAddress = _ZN3WTF3URL15hostIsIPAddressENS_10StringViewE(entryHostView);
    if (!Equal(entryProtocol, Protocol(origin.data))) return false;
    if (IsEmpty(entryHost)) return true;
    const auto& host = Host(origin.data);
    if (Equal(entryHost, host)) return true;
    const auto hostView = ViewOf(host);
    if (!treatIPAddressAsDomain && (entryHostIsIPAddress || _ZN3WTF3URL15hostIsIPAddressENS_10StringViewE(hostView))) return false;
    return hostView.length > entryHostView.length
        && NKWebKit::WtfAbi::CodeUnitAt(hostView, hostView.length - entryHostView.length - 1) == u'.'
        && EndsWith(hostView, entryHostView);
}

