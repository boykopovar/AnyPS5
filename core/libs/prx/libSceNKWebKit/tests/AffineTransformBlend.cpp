static bool AlmostEqual(double actual, double expected) {
    return std::abs(actual - expected) <= 1e-12 * std::fmax(1.0, std::abs(expected));
}

static bool Equals(const WebCore::AffineTransform& t, const Matrix& expected) {
    for (std::size_t i = 0; i < expected.size(); ++i) {
        if (!AlmostEqual(t.m_transform[i], expected[i])) return false;
    }
    return true;
}

static WebCore::AffineTransform Make(const Matrix& m) {
    WebCore::AffineTransform t;
    std::memset(&t, 0xA5, sizeof(t));
    _ZN7WebCore15AffineTransformC1Edddddd(&t, m[0], m[1], m[2], m[3], m[4], m[5]);
    return t;
}

static void TestReferenceCases() {
    for (const BlendCase& c : kCases) {
        WebCore::AffineTransform self = Make(c.to);
        const WebCore::AffineTransform from = Make(c.from);
        _ZN7WebCore15AffineTransform5blendERKS0_d(&self, from, c.progress);
        Require(Equals(self, c.expected), c.name);
        Require(Equals(from, c.from), c.name);
    }
}

static void TestEndpoints() {
    for (const BlendCase& c : kCases) {
        WebCore::AffineTransform atStart = Make(c.to);
        _ZN7WebCore15AffineTransform5blendERKS0_d(&atStart, Make(c.from), 0.0);
        Require(Equals(atStart, c.from), c.name);

        WebCore::AffineTransform atEnd = Make(c.to);
        _ZN7WebCore15AffineTransform5blendERKS0_d(&atEnd, Make(c.from), 1.0);
        Require(Equals(atEnd, c.to), c.name);
    }
}

static void TestFromAliasesSelf() {
    const Matrix m{1.0, 0.5, 0.25, 2.0, -7.0, 11.0};
    WebCore::AffineTransform self = Make(m);
    _ZN7WebCore15AffineTransform5blendERKS0_d(&self, self, 0.75);
    Require(Equals(self, m), "aliased");
}

int main() {
    TestReferenceCases();
    TestEndpoints();
    TestFromAliasesSelf();
    return 0;
}
