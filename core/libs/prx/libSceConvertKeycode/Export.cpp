std::uint32_t CharacterEntry(std::size_t layout, std::size_t layer, std::uint16_t keycode) {
    if (keycode >= 256) return 0;
    return CharacterTables[CharacterLayouts[layout][layer]][keycode];
}

char16_t ConvertCharacter(std::uint16_t keycode, std::uint32_t state, std::uint32_t type) {
    if (keycode == 83 || (keycode & 0xFFF8u) == 224) return 0;
    const auto layout = CharacterLayout(type, state);
    const bool shifted = (state & 0x2200u) != 0;
    const bool caps = (state & 0x20000u) != 0;
    if (layout == 0 && caps) {
        if (keycode == 47) return shifted ? 200 : 220;
        if (keycode == 52) return shifted ? 192 : 196;
        if (keycode == 51) return shifted ? 201 : 214;
    }
    const auto& layers = CharacterLayouts[layout];
    if ((state & 0x4000u) != 0 && (layers[2] != 0 || layers[3] != 0)) {
        auto entry = CharacterEntry(layout, shifted ? 3 : 2, keycode);
        if (entry == 0) return static_cast<char16_t>(CharacterEntry(39, 0, keycode));
        if (caps && (entry & 0x10000u) != 0) {
            const auto opposite = CharacterEntry(layout, shifted ? 2 : 3, keycode);
            if (opposite != 0) entry = opposite;
        }
        return static_cast<char16_t>(entry);
    }
    auto entry = CharacterEntry(layout, shifted ? 1 : 0, keycode);
    if (entry == 0) return 0;
    if (caps) {
        if ((type == 26 || type == 29 || type == 39) && (state & 0x4000000u) != 0) {
            entry = CharacterEntry(layout, shifted ? 3 : 0, keycode);
        } else if (type == 32 && !shifted && ((keycode >= 31 && keycode <= 39) || keycode == 47 || keycode == 51)) {
            entry = CharacterEntry(40, 0, keycode);
        } else if ((entry & 0x10000u) != 0) {
            entry = CharacterEntry(layout, shifted ? 0 : 1, keycode);
        }
        if (entry == 0) return 0;
    }
    if ((entry & 0x20000u) != 0) {
        const bool numLock = (state & 0x10000u) != 0;
        if (!numLock && keycode >= 89 && keycode <= 99) return 0;
        entry = CharacterEntry(layout, numLock ? 1 : 0, keycode);
        if (entry == 0) return 0;
    }
    auto character = static_cast<char16_t>(entry);
    if ((state & 0x4000000u) != 0 && type == 24) {
        if ((character >= 12592 && character < 12688) || (character >= 44032 && character < 55216) || (character & 0xFF00u) == 0x1100) {
            if (character >= 4352 && character <= 4370) return KoreanInitial[character - 4352];
            if (character >= 4449 && character <= 4469) return static_cast<char16_t>(character + 8174);
            if (character >= 4520 && character <= 4546) return KoreanFinal[character - 4520];
            return 0;
        }
    }
    if ((state & 0x4000000u) != 0 && type == 30) {
        if ((state & 0x80u) == 0) {
            if (keycode == 5) character = shifted ? 1570 : 1575;
            if (shifted && keycode == 10) character = 1571;
            if (shifted && keycode == 23) character = 1573;
        }
        const auto modifiers = state & 0xFFF8FFFFu;
        if (modifiers == 67117312 || modifiers == 67121152 || modifiers == 67109632 || modifiers == 67113472) {
            constexpr std::array<char16_t, 4> formatting = {0x200D, 0x200C, 0x200E, 0x200F};
            return keycode >= 30 && keycode <= 33 ? formatting[keycode - 30] : 0;
        }
        if ((state & 0x1100u) != 0 && shifted) return 0;
    }
    return character;
}
