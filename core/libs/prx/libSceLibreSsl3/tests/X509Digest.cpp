int main() {
    InitializeHeap();
    CheckRealCertificate();
    CheckEmptyCertificate();
    CheckNullCertificate();
    CheckAllocationFailure();
    CheckNullDigestType();
    CheckDigestFailures();
    CheckEncodingFailures();
    Require(liveBlocks == 0);
    return 0;
}
