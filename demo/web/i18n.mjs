export function translate(locale, key, values = {}) {
    const text = messages[locale]?.[key] ?? messages.en[key] ?? key;
    return text.replace(/\{(\w+)\}/gu, (match, name) => String(values[name] ?? match));
}

export function apply(locale) {
    const entry = locales.find(item => item.code === locale) ?? locales.find(item => item.code === "en");
    document.documentElement.lang = entry.code;
    document.documentElement.dir = entry.direction;
    for (const node of document.querySelectorAll("[data-i18n]")) node.textContent = translate(locale, node.dataset.i18n);
    for (const node of document.querySelectorAll("[data-i18n-attr]")) {
        for (const pair of node.dataset.i18nAttr.split(";")) {
            const [attr, key] = pair.split(":").map(part => part.trim());
            if (attr && key) node.setAttribute(attr, translate(locale, key));
        }
    }
}

export function current() {
    let saved;
    try { saved = localStorage.getItem(STORAGE_KEY); } catch { saved = null; }
    return locales.some(item => item.code === saved) ? saved : "en";
}

export function set(locale) {
    try { localStorage.setItem(STORAGE_KEY, locale); } catch {}
    apply(locale);
}
