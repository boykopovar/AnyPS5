import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";

const context = vm.createContext({ Uint8Array, Blob, ReadableStream, WritableStream, TransformStream, AbortController, DataView });
const module = new vm.SourceTextModule(readFileSync(new URL("../archive.mjs", import.meta.url), "utf8"), { context });
await module.link(async name => {
  const exports = name.startsWith("https:") ? { BlobReader: class {}, Uint8ArrayReader: class {}, ZipReader: class {}, ZipWriter: class {}, configure() {} } : { batchMemoryEstimate() {}, batchOutputDirectory() {}, memoryEstimate() {}, MEMORY_LIMIT: 0 };
  return new vm.SyntheticModule(Object.keys(exports), function() { for (const [key, value] of Object.entries(exports)) this.setExport(key, value); }, { context });
});
await module.evaluate();
const { DirectoryWriter } = module.namespace;
let scenarios = 0;
let opened = 0;
await assert.rejects(new DirectoryWriter({ async file() { opened++; return new WritableStream(); } }).add("file", { async init() { throw new Error("init failed"); } }), /init failed/);
assert.equal(opened, 0);
scenarios++;
let directory = false;
await new DirectoryWriter({ async directory() { directory = true; }, async file() { throw new Error("unexpected file"); } }).add("dir/", null, { directory: true });
assert.equal(directory, true);
scenarios++;
const order = [];
const chunks = [];
let closed = false;
const output = new WritableStream({ write(value) { chunks.push(new Uint8Array(value)); }, close() { closed = true; } });
const source = { size: 150000, async init() { order.push("init"); }, async readUint8Array(offset, count) { assert.ok(count <= 65536); return Uint8Array.from({ length: count }, (_, index) => (offset + index) % 251); } };
await new DirectoryWriter({ async file() { order.push("file"); return output; } }).add("file", source);
assert.deepEqual(order, ["init", "file"]);
assert.equal(Buffer.concat(chunks).length, 150000);
assert.equal(Buffer.concat(chunks)[149999], 149999 % 251);
assert.equal(closed, true);
assert.equal(output.locked, false);
scenarios++;
let aborted = false;
const brokenOutput = new WritableStream({ abort() { aborted = true; } });
await assert.rejects(new DirectoryWriter({ async file() { return brokenOutput; } }).add("file", { size: 1, async init() {}, async readUint8Array() { throw new Error("read failed"); } }), /read failed/);
assert.equal(aborted, true);
assert.equal(brokenOutput.locked, false);
scenarios++;
const streaming = new ReadableStream({ start(controller) { controller.enqueue(new Uint8Array(150000)); controller.close(); } });
let maximumWrite = 0;
let total = 0;
const streamed = new WritableStream({ write(value) { maximumWrite = Math.max(maximumWrite, value.length); total += value.length; } });
await new DirectoryWriter({ async file() { return streamed; } }).add("file", streaming);
assert.equal(total, 150000);
assert.ok(maximumWrite <= 65536);
assert.equal(streaming.locked, false);
assert.equal(streamed.locked, false);
scenarios++;
let cancelled = false;
const pending = new ReadableStream({ pull(controller) { controller.enqueue(new Uint8Array([1])); }, cancel() { cancelled = true; } });
const rejected = new WritableStream({ write() { throw new Error("write failed"); } });
await assert.rejects(new DirectoryWriter({ async file() { return rejected; } }).add("file", pending), /write failed/);
assert.equal(cancelled, true);
assert.equal(pending.locked, false);
assert.equal(rejected.locked, false);
scenarios++;
console.log(JSON.stringify({ scenarios }));
